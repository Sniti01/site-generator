  check('геометрия: служебные ключи не вьюпорты', '', строк(сравнитьГеометрию({ снято: '2026-09-11', '1440': { высота: 1, слои: {} } }, { '1440': { высота: 1, слои: {} } })), 'дата и сборка в geometria.json — не размеры окна');
  check('геометрия: отступ кадров блоков другой — одна строка', 'отступ кадров блоков:НЕТ', строк(сравнитьГеометрию({ отступ_блока: 100, '1440': { высота: 1, слои: {} } }, { отступ_блока: 92, '1440': { высота: 1, слои: {} } })), 'число входит в определение кадра блока (П41): другой отступ — другой драйвер, не правка');
  check('геометрия: отступ записан только у снятого', 'отступ кадров блоков:НЕТ', строк(сравнитьГеометрию({ '1440': { высота: 1, слои: {} } }, { отступ_блока: 100, '1440': { высота: 1, слои: {} } })), 'эталон без отступа против съёмки с кадрами блоков — сказано');

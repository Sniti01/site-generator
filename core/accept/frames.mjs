/** Готовность страницы: шрифты разложены, изображения догружены. */
export const ГОТОВНОСТЬ = `await document.fonts.ready;
const imgs = [...document.images];
await Promise.all(imgs.map(i => i.complete ? null : new Promise(r => { i.onload = i.onerror = r; })));
({ шрифты: 'ready', изображений: imgs.length, загружено: imgs.filter(i => i.complete && i.naturalWidth > 0).length })`;

/**
 * Прокрутка до низа и обратно: без неё ленивые изображения не занимают место,
 * и полный кадр выходит короче — именно отсюда разные высоты у старых снимков
 * `.impeccable/review/` (8678 и 8659).
 *
 * **Ступенями, а не одним прыжком.** Ленивое изображение грузится, когда
 * попадает в поле зрения; мгновенный прыжок вниз и обратно середину страницы
 * не показывает. Измерено 2026-09-09 на 1440×900: один прыжок будит 3 из 11
 * изображений, ступени по 0,9 высоты окна — 11 из 11. Цена пропуска — полный
 * кадр расходится с эталоном на 2 131 290 субпикселей из 38 098 080.
 */
// `'instant'`, а не `'auto'`: по спецификации `'auto'` значит «как велит CSS»,
// а `src/styles/global.css` ставит `html { scroll-behavior: smooth }`.
export const ПРОКРУТКА = `const шаг = Math.round(window.innerHeight * 0.9);
for (let y = 0; y <= document.body.scrollHeight; y += шаг) {
  window.scrollTo({ top: y, behavior: 'instant' });
  await new Promise(r => setTimeout(r, 60));
}
window.scrollTo({ top: document.body.scrollHeight, behavior: 'instant' });
await new Promise(r => setTimeout(r, 400));
window.scrollTo({ top: 0, behavior: 'instant' });
await new Promise(r => setTimeout(r, 200));
({ высота: document.body.scrollHeight, scrollY: window.scrollY })`;

/**
 * Прокрутка к кадру слоя — **по якорю**, не к числу (П39). Слой центрируется
 * в окне: `y = round(offsetTop + (высота слоя − высота окна) / 2)`, где
 * `offsetTop` и высота — из `getBoundingClientRect()` с точностью 0,01,
 * а округление стоит **снаружи**: `offsetTop` на живой странице дробный
 * (у четырёх слоёв из пяти на 2026-09-11), а цель прокрутки — целый пиксель.
 * Это то же правило центрирования, которым 2026-09-09 получены литералы
 * 892 / 1818 / 6006, но не та же арифметика: тогда складывали целые
 * `offsetTop` и округлённую половину, и на дробных входах результат может
 * отличаться на 1 px. Судья от этого не страдает: обе стороны любой сверки —
 * эталон после пересъёмки и снятое — идут через этот же скрипт.
 *
 * Сдвиг сверху при этом не теряется: скрипт возвращает `offsetTop` и высоту
 * страницы, и `check` сверяет их с записанными (`ГЕОМЕТРИЯ`, `geometria.json`).
 *
 * Отсутствие якоря — отказ, не «встало где-то»: кадр без своего слоя —
 * не кадр этого слоя.
 */
export const К_ЯКОРЮ = (id) => `const слой = document.getElementById(${JSON.stringify(id)});
if (!слой) throw new Error('нет якоря #' + ${JSON.stringify(id)});
const рамка = слой.getBoundingClientRect();
const offsetTop = Math.round((рамка.top + window.scrollY) * 100) / 100;
const высота = Math.round(рамка.height * 100) / 100;
const y = Math.round(offsetTop + (высота - window.innerHeight) / 2);
window.scrollTo({ top: y, behavior: 'instant' });
await new Promise(r => setTimeout(r, 200));
({ якорь: ${JSON.stringify(id)}, offsetTop, высота, ожидали: y, scrollY: window.scrollY, высотаСтраницы: document.body.scrollHeight })`;

/**
 * Отступ кадра блока от верха окна, px. Равен тому, куда сама страница ставит
 * заголовок по клику якоря оглавления: `scroll-margin-top` заголовков —
 * `--header-h` (68) + `--space-lg` (32). Кадр блока показывает блок так, как
 * его видит читатель, перейдя по ссылке «на этой странице». Под липкой шапкой
 * (коробка 69 px: 68 + линия 1 px) остаётся 31 px воздуха. **Число входит
 * в определение кадра**: съёмка пишет его в `geometria.json` (`отступ_блока`),
 * `check` сверяет с эталоном и при расхождении говорит одной строкой.
 */
export const ОТСТУП_БЛОКА = 100;

/**
 * Прокрутка к кадру **блока** — от его заголовка, не по центру (П41, ответ 5:
 * блоки страницы игры ниже первого экрана получают судей). Слой центрируют,
 * потому что он высотой с окно; блок — оглавление, галерея, вердикт, список,
 * призыв — короче окна и читается сверху вниз. Формула:
 * `y = max(0, round(offsetTop − отступ))`, где `offsetTop` — верх заголовка
 * из `getBoundingClientRect()` с точностью 0,01, `отступ` — `ОТСТУП_БЛОКА`.
 * Заголовок встаёт на `отступ` px от верха окна; **остаток окна занимает
 * следующий блок или подвал — кадр блока судит и их**, и таблица маппинга
 * «кадр → пункт» обязана это учитывать (дифф в кадре вердикта может прийти
 * из правки списка ссылок под ним).
 *
 * Якорь — `id` заголовка (`…-tytul`): секции блоков своих `id` не несут,
 * а вешать их ради съёмки — правка страниц ради инструмента.
 *
 * Возвращает то же, что `К_ЯКОРЮ`, плюс `отступ`; нет якоря — отказ.
 * Если до низа страницы меньше окна, `scrollY` не дойдёт до `ожидали` —
 * драйвер сверяет их после каждого наведения и останавливается (шаги 7–8
 * ПОРЯДКА): кадр «где встало» не кадр блока.
 */
export const К_ВЕРХУ = (id, отступ = ОТСТУП_БЛОКА) => `const заголовок = document.getElementById(${JSON.stringify(id)});
if (!заголовок) throw new Error('нет якоря #' + ${JSON.stringify(id)});
const рамка = заголовок.getBoundingClientRect();
const offsetTop = Math.round((рамка.top + window.scrollY) * 100) / 100;
const высота = Math.round(рамка.height * 100) / 100;
const y = Math.max(0, Math.round(offsetTop - ${Number(отступ)}));
window.scrollTo({ top: y, behavior: 'instant' });
await new Promise(r => setTimeout(r, 200));
({ якорь: ${JSON.stringify(id)}, отступ: ${Number(отступ)}, offsetTop, высота, ожидали: y, scrollY: window.scrollY, высотаСтраницы: document.body.scrollHeight })`;

/**
 * Геометрия страницы для сверки числом: условия съёмки, высота страницы
 * и положение каждого слоя по якорю. Снимается при `scrollY = 0` после
 * `ПРОКРУТКА`, когда все изображения заняли место. Результат для каждого
 * вьюпорта складывается в `geometria.json` рядом с кадрами — той же формы,
 * что у эталона.
 *
 * **Условия съёмки записываются**, потому что раскладка считается не по
 * `innerWidth`, а по `clientWidth`: видимая полоса прокрутки отнимает
 * у раскладки 10 px, и на 390 это меняет высоту страницы и положение слоёв
 * (измерено 2026-09-11: 11545 против 11514). Без записи такой сдвиг
 * читался бы как правка вёрстки, которой не было.
 *
 * **Якорь без элемента — отказ**, как у `К_ЯКОРЮ`: `null` в геометрии
 * эталона — это опечатка в списке якорей, и ей нельзя дать лечь в файл молча.
 */
export const ГЕОМЕТРИЯ = (ids) => `({
  вьюпорт: { w: window.innerWidth, h: window.innerHeight,
    clientWidth: document.documentElement.clientWidth, clientHeight: document.documentElement.clientHeight,
    dpr: window.devicePixelRatio },
  высота: document.body.scrollHeight,
  слои: Object.fromEntries(${JSON.stringify(ids)}.map(id => {
    const el = document.getElementById(id);
    if (!el) throw new Error('нет якоря #' + id);
    const r = el.getBoundingClientRect();
    return [id, { offsetTop: Math.round((r.top + window.scrollY) * 100) / 100, высота: Math.round(r.height * 100) / 100 }];
  }))
})`;

const ширины = (г) => Object.keys(г ?? {}).filter((k) => /^\d+$/.test(k));
const число = (x) => typeof x === 'number' && Number.isFinite(x);
const разница = (с, э) => Math.round((с - э) * 100) / 100;

/**
 * Сколько в эталоне есть чего сверять: вьюпортов и слоёв. Печатается
 * рядом со словом «совпала», потому что «совпала» при нуле сравнённого —
 * ложный пропуск (находка проверки 2026-09-11).
 */
export function счётГеометрии(эталон) {
  const w = ширины(эталон);
  return { вьюпортов: w.length, слоёв: w.reduce((n, k) => n + Object.keys(эталон[k]?.слои ?? {}).length, 0) };
}

/**
 * Сверка геометрии: эталонная против снятой, обе — `{ '<ширина>': { вьюпорт,
 * высота, слои: { <якорь>: { offsetTop, высота } } } }`. Возвращает список
 * строк; пустой список — геометрия совпала **и было что сравнивать**.
 * Чистая функция: её проверяет самопроверка.
 *
 * Каждая строка несёт `что` и либо числа (`эталон`, `снято`, `сдвиг`,
 * округлённый до 0,01), либо `причина` словами — для всего, что не число:
 * вьюпорт не снят или не записан, слой без якоря с любой стороны, поле
 * не записано, условия съёмки другие. Разыменования `null` тут нет
 * по устройству: любая дыра в данных становится строкой, а не падением.
 *
 * Обход идёт по **объединению** ключей эталона и снятого: лишний вьюпорт
 * или слой у снятого называется, а не игнорируется — иначе эталон без
 * слоёв делал бы любую съёмку «совпавшей».
 *
 * Условия съёмки сверяются **первыми**: при другой ширине раскладки
 * (`clientWidth`) сдвиги слоёв — следствие условий, а не правки, и вместо
 * их списка печатается одна строка.
 */
export function сравнитьГеометрию(эталон, снятое) {
  const строки = [];
  const шЭ = ширины(эталон);
  if (!шЭ.length) {
    строки.push({ что: 'эталон', причина: 'нет ни одного вьюпорта — сверять нечего' });
    return строки;
  }
  // Отступ кадров блоков — условие съёмки, входящее в определение кадра:
  // другой отступ сдвигает все кадры блоков, а пиксель прочитал бы это как правку.
  const оЭ = эталон.отступ_блока;
  const оС = снятое?.отступ_блока;
  if (число(оЭ) && число(оС) && оЭ !== оС) {
    строки.push({ что: 'отступ кадров блоков', причина: `другой (${оС} ≠ ${оЭ}) — кадры блоков не сравнимы, сперва уравнять драйвер` });
  } else if (число(оЭ) !== число(оС)) {
    строки.push({ что: 'отступ кадров блоков', причина: `записан только у ${число(оЭ) ? 'эталона' : 'снятого'}` });
  }
  const все = [...new Set([...шЭ, ...ширины(снятое)])].sort((a, b) => Number(a) - Number(b));
  for (const w of все) {
    const э = эталон[w];
    const с = снятое?.[w];
    if (!э) {
      строки.push({ что: `вьюпорт ${w}`, причина: 'снят, но в эталоне не записан' });
      continue;
    }
    if (!с) {
      строки.push({ что: `вьюпорт ${w}`, причина: 'в эталоне есть, не снят' });
      continue;
    }

    const уЭ = э.вьюпорт;
    const уС = с.вьюпорт;
    if (уЭ && уС) {
      const другие = ['clientWidth', 'clientHeight', 'dpr']
        .filter((k) => число(уЭ[k]) && число(уС[k]) && уЭ[k] !== уС[k])
        .map((k) => `${k} ${уС[k]} ≠ ${уЭ[k]}`);
      if (другие.length) {
        строки.push({ что: `условия съёмки ${w}`, причина: `другие (${другие.join(', ')}) — сдвиги ниже не сверяются, сперва уравнять драйвер` });
        continue;
      }
    }

    if (!число(э.высота) || !число(с.высота)) {
      строки.push({ что: `высота ${w}`, причина: `поле не записано (${!число(э.высота) ? 'эталон' : 'снято'})` });
    } else if (э.высота !== с.высота) {
      строки.push({ что: `высота ${w}`, вид: 'страница', эталон: э.высота, снято: с.высота, сдвиг: разница(с.высота, э.высота) });
    }

    const слоиЭ = э.слои ?? {};
    const слоиС = с.слои ?? {};
    for (const якорь of [...new Set([...Object.keys(слоиЭ), ...Object.keys(слоиС)])]) {
      const эс = слоиЭ[якорь];
      const сс = слоиС[якорь];
      if (!эс) {
        строки.push({ что: `${w} #${якорь}`, причина: !(якорь in слоиЭ) ? 'снят, но в эталоне не записан' : 'эталон без якоря (null) — опечатка в списке при съёмке эталона' });
        continue;
      }
      if (!сс) {
        строки.push({ что: `${w} #${якорь}`, причина: !(якорь in слоиС) ? 'в эталоне есть, не снят' : 'нет якоря на странице (null)' });
        continue;
      }
      for (const [поле, вид] of [['offsetTop', 'выше слоя'], ['высота', 'внутри слоя']]) {
        if (!число(эс[поле]) || !число(сс[поле])) {
          строки.push({ что: `${w} #${якорь} ${поле}`, причина: `поле не записано (${!число(эс[поле]) ? 'эталон' : 'снято'})` });
        } else if (эс[поле] !== сс[поле]) {
          строки.push({ что: `${w} #${якорь} ${поле}`, вид, эталон: эс[поле], снято: сс[поле], сдвиг: разница(сс[поле], эс[поле]) });
        }
      }
    }
  }
  return строки;
}


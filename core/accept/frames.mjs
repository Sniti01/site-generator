    console.log('СКРИПТ «ПРОКРУТКА»:');
    console.log(ПРОКРУТКА);
    console.log('');
    console.log('СКРИПТ «ГЕОМЕТРИЯ» (условия съёмки, высота страницы и слои по якорю), для якорей таблицы главной:');
    console.log(ГЕОМЕТРИЯ(ЯКОРЯ_ПРИМЕРА));
    console.log('');
    console.log(`СКРИПТ «К ЯКОРЮ» (оконный кадр слоя, П39), пример для #${ЯКОРЯ_ПРИМЕРА[0]}:`);
    console.log(К_ЯКОРЮ(ЯКОРЯ_ПРИМЕРА[0]));

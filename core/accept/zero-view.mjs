#!/usr/bin/env node
/**
 * Приёмка: предикат «нулевая витрина».
 *
 *   node core/accept/zero-view.mjs <dist-до> <dist-после> --сайт <папка сайта> \
 *        --новые <файл,файл,…>
 *
 * Заменяет «побайтовый ноль» у сессий, которые обещают, что **вид не меняется**.
 * Сессии, меняющие вид намеренно, судятся прежним протоколом `MIGRATION.md` §6:
 * локализация диффы, затем пиксель против `_baseline/`.
 *
 * **Почему ноль на `index.html` недостижим и чем он заменён.** Astro именует
 * собранный лист хешем его содержимого, а `index.html` ссылается на лист этим
 * именем. Любое добавленное правило меняет содержимое листа → меняет имя →
 * меняет `href`. Измерено 2026-09-09: один файл под `src/` со словом
 * `underline` дал `Base.CxtPq8QU.css` → `Base.DWnGvTLu.css`, и `index.html`
 * перестал быть побайтово равным, оставшись равным **после приведения имён
 * с хешем**. Поэтому проверка 1 требует ноль после этой — уже записанной
 * и уже применявшейся — нормализации, а проверка 2 стережёт то, что
 * нормализация скрывать не должна: число и порядок самих ссылок.
 *
 * **Шесть проверок, все машинные.** Требования владельца от 2026-09-09.
 *
 *   1. `index.html` побайтово равен после приведения имён с хешем.
 *   2. Число и порядок ссылок на ресурсы в `index.html` не изменились.
 *   3. В манифесте расходятся только листы стилей, и только парами
 *      «удалён X.<хеш1>.css / добавлен X.<хеш2>.css» с тем же базовым именем.
 *   4. Ни одно существующее правило не изменено и не удалено: мультимножество
 *      троек «до» обязано быть подмножеством «после».
 *   5. Каждое добавленное правило — утилита сканера с нового файла: стек
 *      условий содержит `@layer utilities`; селектор — ровно один класс без
 *      `data-astro-cid-*`; имя класса встречается отдельным словом хотя бы
 *      в одном новом файле и НЕ встречается ни в одном файле, существовавшем
 *      до правки.
 *   6. Печатается число добавленных правил, их список и файл-источник каждого.
 *
 * **Код возврата здесь — приговор, и это отличие от прочих инструментов
 * приёмки.** У `manifest.mjs` и `pixels.mjs` вердикт выносит человек по выводу;
 * здесь предикат либо выполняется, либо нет, и разбирать нечего:
 * `0` — выполняется, `1` — не выполняется, `2` — инструмент не смог прочитать
 * вход.
 */

import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { extname, join, relative, sep } from 'node:path';
import { snapshot } from './manifest.mjs';
import { measure } from './css-triples.mjs';
import { flattenScopes, normalizeHashedNames } from './html-diff.mjs';

/** Разделитель тройки — тот же U+241F, что в `css-triples.mjs`. */
const SEP = '␟';

/**
 * Ссылки на ресурсы в порядке документа: листы стилей и скрипты с `src`.
 * Хеши в именах погашены — проверка 2 сторожит число и порядок, а не имена.
 */
export function ссылки(html) {
  const out = [];
  for (const m of html.matchAll(/<(?:link|script)\b[^>]*>/gi)) {
    const тег = m[0];
    const link = /^<link/i.test(тег);
    if (link && !/rel\s*=\s*["']?stylesheet/i.test(тег)) continue;
    const адрес = тег.match(link ? /href\s*=\s*["']([^"']+)["']/i : /src\s*=\s*["']([^"']+)["']/i);
    if (адрес) out.push(normalizeHashedNames(адрес[1]).html);
  }
  return out;
}

/**
 * Селектор — ровно один класс? Утилита сканера всегда такова, и это отличает
 * её от правил витрины и ядра, которые несут скрут в квадратных скобках.
 * Возвращает имя класса без экранирования CSS или `null`.
 */
export function одинКласс(селектор) {
  const s = селектор.trim();
  if (!s.startsWith('.')) return null;
  const тело = s.slice(1);
  let i = 0;
  let имя = '';
  while (i < тело.length) {
    const ch = тело[i];
    if (ch === '\\') {
      if (i + 1 >= тело.length) return null;
      имя += тело[i + 1];
      i += 2;
      continue;
    }
    // Любой неэкранированный символ, начинающий новую часть селектора, — отказ.
    if (/[\s,.:>+~[\]()#*|=$^"']/.test(ch)) return null;
    имя += ch;
    i += 1;
  }
  return имя.length ? имя : null;
}

/** Слово целиком, а не подстрока: `block` не должен ловиться внутри `blocks`. */
export function словоЕсть(текст, слово) {
  const щит = слово.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
  return new RegExp(`(^|[^A-Za-z0-9_-])${щит}([^A-Za-z0-9_-]|$)`).test(текст);
}

/** Тройка → её части. Обратный разбор точен: разделитель в CSS не встречается. */
export function частиТройки(тройка) {
  const [условия, селектор, объявления] = тройка.split(SEP);
  return { условия, селектор, объявления };
}

/**
 * Правило — утилита сканера с нового файла?
 * Три условия сразу, и каждое названо отдельно, чтобы отказ был читаем.
 *
 * **Чего здесь НЕТ и почему.** Первая редакция требовала четвёртым условием,
 * чтобы имя класса не встречалось ни в одном файле, существовавшем до правки:
 * «раз утилиты не было, значит и слова не было». Условие снято, потому что
 * посылка неверна, и это измерено на первом же прогоне 2026-09-09: слово
 * `underline` лежит в `core/blocks/LinkColumns.astro` с самого начала, а
 * утилита `.underline` до правки не эмитилась. Сканер извлекает кандидатов
 * своими правилами, и повторять их здесь значило бы завести второй Tailwind
 * внутри приёмки. Наличие слова в старом файле остаётся **примечанием**
 * в выводе, а не отказом.
 */
export function утилитаЛи(тройка, новыеТексты, старыеТексты) {
  const { условия, селектор } = частиТройки(тройка);
  if (!условия.includes('@layer utilities')) {
    return { да: false, почему: 'правило вне `@layer utilities`' };
  }
  if (селектор.includes('data-astro-cid-')) {
    return { да: false, почему: 'селектор несёт скрут — это не утилита' };
  }
  const класс = одинКласс(селектор);
  if (!класс) {
    return { да: false, почему: `селектор не «ровно один класс»: ${селектор}` };
  }
  const источник = [...новыеТексты].find(([, текст]) => словоЕсть(текст, класс));
  if (!источник) {
    return { да: false, почему: `слово «${класс}» не найдено ни в одном новом или изменённом файле` };
  }
  const старый = [...старыеТексты].find(([, текст]) => словоЕсть(текст, класс));
  return { да: true, класс, файл: источник[0], такжеСтарый: старый ? старый[0] : null };
}

/* — вспомогательное чтение — */

function обойти(каталог, корень, out, годится) {
  if (!existsSync(каталог)) return out;
  for (const имя of readdirSync(каталог).sort()) {
    const путь = join(каталог, имя);
    if (statSync(путь).isDirectory()) обойти(путь, корень, out, годится);
    else if (годится(путь)) out.set(relative(корень, путь).split(sep).join('/'), readFileSync(путь, 'utf8'));
  }
  return out;
}

/** Всё, что видит сканер Tailwind: `src/` сайта целиком и `.astro` ядра. */
export function сканируемыеФайлы(сайт, корень) {
  const текстовые = (путь) => !/\.(png|jpe?g|webp|avif|gif|ico|woff2?|ttf|otf|mp4|webm|pdf|xlsx)$/i.test(путь);
  const out = new Map();
  обойти(join(сайт, 'src'), корень, out, текстовые);
  обойти(join(корень, 'core'), корень, out, (п) => extname(п) === '.astro');
  return out;
}

function листыВПорядкеСсылок(dist, html) {
  const порядок = [];
  for (const m of html.matchAll(/<link\b[^>]*>/gi)) {
    if (!/rel\s*=\s*["']?stylesheet/i.test(m[0])) continue;
    const адрес = m[0].match(/href\s*=\s*["']([^"']+)["']/i);
    if (адрес) порядок.push(адрес[1].replace(/^\//, ''));
  }
  return порядок.map((rel) => readFileSync(join(dist, rel.split('/').join(sep)), 'utf8')).join('\n');
}

const считать = (xs) => {
  const m = new Map();
  for (const x of xs) m.set(x, (m.get(x) ?? 0) + 1);
  return m;
};

/* — сам предикат — */

export function нулеваяВитрина({ доDist, послеDist, сайт, корень, новые }) {
  const провалы = [];
  const заметки = [];

  const доHtml = readFileSync(join(доDist, 'index.html'), 'utf8');
  const послеHtml = readFileSync(join(послеDist, 'index.html'), 'utf8');

  // 1. index.html после приведения имён с хешем.
  const a = normalizeHashedNames(доHtml).html;
  const b = normalizeHashedNames(послеHtml).html;
  заметки.push(
    `1. index.html: ${доHtml.length} → ${послеHtml.length} байт; после приведения имён ${a === b ? 'РАВНЫ' : 'НЕ равны'}`
  );
  if (a !== b) провалы.push('1. index.html расходится не только именем листа с хешем');

  // 2. Число и порядок ссылок.
  const сА = ссылки(доHtml);
  const сБ = ссылки(послеHtml);
  заметки.push(`2. ссылок на ресурсы: ${сА.length} → ${сБ.length}`);
  if (сА.length !== сБ.length || сА.some((v, i) => v !== сБ[i])) {
    провалы.push(`2. число или порядок ссылок изменились: [${сА.join(', ')}] → [${сБ.join(', ')}]`);
  }

  // 3. Манифест: расходятся только листы, и только парами с тем же именем.
  const мА = snapshot(доDist);
  const мБ = snapshot(послеDist);
  const кА = new Map(мА.файлы.map((f) => [f.file, f]));
  const кБ = new Map(мБ.файлы.map((f) => [f.file, f]));
  const база = (p) => p.replace(/\.[A-Za-z0-9_-]{8}\.css$/, '.css');
  const css = (p) => p.endsWith('.css');
  const ушли = [...кА.keys()].filter((k) => !кБ.has(k));
  const пришли = [...кБ.keys()].filter((k) => !кА.has(k));
  const менялись = [...кА.keys()].filter((k) => кБ.has(k) && кА.get(k).sha256 !== кБ.get(k).sha256);
  заметки.push(
    `3. манифест: ${мА.файлов} → ${мБ.файлов} файлов; ушло ${ушли.length}, пришло ${пришли.length}, изменено ${менялись.length}`
  );
  for (const f of менялись) {
    if (f !== 'index.html') провалы.push(`3. изменён файл, который меняться не должен: ${f}`);
  }
  for (const f of [...ушли, ...пришли]) {
    if (!css(f)) провалы.push(`3. расхождение вне листа стилей: ${f}`);
  }
  const базыА = считать(ушли.filter(css).map(база));
  const базыБ = считать(пришли.filter(css).map(база));
  for (const [k, n] of базыА) {
    if ((базыБ.get(k) ?? 0) !== n) провалы.push(`3. лист ${k} исчез без замены с тем же базовым именем`);
  }
  for (const [k, n] of базыБ) {
    if ((базыА.get(k) ?? 0) !== n) провалы.push(`3. появилось новое базовое имя листа: ${k}`);
  }

  // 4 и 5. Тройки CSS: скруты гасятся плоско, как велит REUSE §6.
  const cssА = flattenScopes(листыВПорядкеСсылок(доDist, доHtml)).html;
  const cssБ = flattenScopes(листыВПорядкеСсылок(послеDist, послеHtml)).html;
  const тА = считать(measure(cssА).тройки);
  const тБ = считать(measure(cssБ).тройки);
  let правилДо = 0;
  let правилПосле = 0;
  for (const n of тА.values()) правилДо += n;
  for (const n of тБ.values()) правилПосле += n;
  заметки.push(`4. правил CSS: ${правилДо} → ${правилПосле}`);
  for (const [t, n] of тА) {
    const m = тБ.get(t) ?? 0;
    if (m < n) провалы.push(`4. правило изменено или удалено: ${частиТройки(t).селектор} (было ${n}, стало ${m})`);
  }

  const добавленные = [];
  for (const [t, n] of тБ) {
    const было = тА.get(t) ?? 0;
    for (let i = 0; i < n - было; i += 1) добавленные.push(t);
  }

  const все = сканируемыеФайлы(сайт, корень);
  const новыеТексты = new Map();
  const старыеТексты = new Map();
  for (const [путь, текст] of все) (новые.has(путь) ? новыеТексты : старыеТексты).set(путь, текст);
  for (const путь of новые) {
    if (!все.has(путь)) заметки.push(`   ! назван новым, но сканером не виден: ${путь}`);
  }

  const разбор = добавленные.map((t) => ({ тройка: t, ...утилитаЛи(t, новыеТексты, старыеТексты) }));
  for (const r of разбор) {
    if (!r.да) провалы.push(`5. добавленное правило не опознано как утилита: ${частиТройки(r.тройка).селектор} — ${r.почему}`);
  }

  return { провалы, заметки, добавленные: разбор, правилДо, правилПосле };
}

/* — запуск — */

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split(sep).join('/'))) {
  const argv = process.argv.slice(2);
  const позиционные = argv.filter((a) => !a.startsWith('--'));
  const взять = (имя) => {
    const i = argv.indexOf(имя);
    return i >= 0 ? argv[i + 1] : null;
  };
  const [доDist, послеDist] = позиционные;
  const сайт = взять('--сайт');
  const списокНовых = взять('--новые');
  if (!доDist || !послеDist || !сайт) {
    console.error('node core/accept/zero-view.mjs <dist-до> <dist-после> --сайт <папка сайта> --новые <файл,файл>');
    console.error('  пути новых файлов — от корня репозитория, через запятую');
    process.exit(2);
  }
  if (!existsSync(join(доDist, 'index.html')) || !existsSync(join(послеDist, 'index.html'))) {
    console.error('нет index.html в одной из сборок');
    process.exit(2);
  }
  const корень = process.cwd();
  const новые = new Set(
    (списокНовых ?? '')
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean)
  );

  const r = нулеваяВитрина({ доDist, послеDist, сайт, корень, новые });

  console.log('ПРЕДИКАТ «НУЛЕВАЯ ВИТРИНА»');
  for (const з of r.заметки) console.log(`  ${з}`);
  console.log('');
  console.log(`6. добавленных правил: ${r.добавленные.length}`);
  for (const d of r.добавленные) {
    const { селектор, объявления } = частиТройки(d.тройка);
    const хвост = d.да ? ` ← ${d.файл}${d.такжеСтарый ? ` (слово есть и в ${d.такжеСтарый} — примечание, не отказ)` : ''}` : '';
    console.log(`   ${d.да ? 'утилита' : 'ЧУЖОЕ  '} ${селектор} { ${объявления} }${хвост}`);
  }
  console.log('');
  if (r.провалы.length) {
    console.log('ПРЕДИКАТ НЕ ВЫПОЛНЯЕТСЯ:');
    for (const п of r.провалы) console.log(`  ${п}`);
    process.exit(1);
  }
  console.log('Предикат выполняется: витрина нулевая.');
}

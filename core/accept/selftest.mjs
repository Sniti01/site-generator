  check('шум: дифф в зоне > макс — вне', 'вне:1/3', кратко(оц(э, с1(5, 5, 0, 3), [З()])), 'Δ3 при макс 2 — превышение порога — отказ');
  check('шум: дифф вне рамки — вне', 'вне:1/1', кратко(оц(э, с1(20, 5, 0, 1), [З({ рамка: { x: 0, y: 0, w: 10, h: 10 } })])), 'зона есть, но точка не в её рамке');
  check('шум: рамка null — весь кадр', 'в:z=1/1', кратко(оц(э, с1(59, 19, 2, -1), [З({ рамка: null })])), 'последний пиксель кадра — внутри');
  const св = (цвет) => { const e = кадр(4, 4, цвет); return кратко(оц(e, ткнуть(клон(e), 1, 1, 0, 1), [З({ только_светлые: true, порог_яркости: 128 })])); };
  check('шум: только светлые — светлый Δ1 в допуске', 'в:z=1/1', св([200, 200, 200]), 'яркость 200 ≥ порога 128');
  check('шум: только светлые — тёмный Δ1 вне', 'вне:1/1', св([13, 12, 10]), 'фон --bg (13, 12, 10) ниже порога — дифф не списывается');
  check('шум: яркость ровно порог — светлый', 'в:z=1/1', св([128, 0, 0]), 'граница включительно: яркость ≥ порог; яркость — max(R, G, B)');

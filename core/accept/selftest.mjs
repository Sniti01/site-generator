#!/usr/bin/env node
/**
 * Самопроверка инструментов приёмки.
 *
 *   node core/accept/selftest.mjs <папка сайта>
 *
 * Инструмент приёмки, которого никто не видел считающим правильно, —
 * обещание, а не проверка. Тот же довод, по которому у гейта структуры
 * есть `--selftest`.
 *
 * Проверка здесь особая: инструменты обязаны **воспроизвести числа, уже
 * записанные в отчётах прошлых сессий**. Числа взяты не из головы и не из
 * сегодняшнего прогона — они лежат в `docs/reports/` и в `MIGRATION.md` §6,
 * и если новый код даёт другие, разошлись либо код, либо сборка, и разбираться
 * надо до того, как инструментом начнут принимать выносы.
 *
 * Требуется собранный `dist/` сайта и снятый `_baseline/`.
 */

import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { compare, snapshot } from './manifest.mjs';
import { measure } from './css-triples.mjs';
import { decodePng, comparePixels } from './pixels.mjs';
import { normalizeScopes, flattenScopes, scopeLedger } from './html-diff.mjs';
import { одинКласс, словоЕсть, ссылки, утилитаЛи } from './zero-view.mjs';

const site = process.argv[2];
if (!site) {
  console.error('node core/accept/selftest.mjs <папка сайта>');
  process.exit(2);
}

const dist = join(site, 'dist');
const baseline = join(site, '_baseline');
if (!existsSync(dist)) {
  console.error(`нет сборки: ${dist} — самопроверке нужен свежий npm run build`);
  process.exit(2);
}

const cases = [];
const check = (имя, ждём, факт, откуда) =>
  cases.push({ имя, ждём, факт, откуда, ok: String(ждём) === String(факт) });

/* — манифест: снимок и сверка на РУКОПИСНОЙ папке —
   Решение владельца 2026-09-09. Прежде здесь стояли три утверждения о форме
   живой сборки: «файлов в dist/ 50», «файлов CSS в сборке 1» и «правил CSS
   331». Все три — константы, которые двигают руками: сессия 4 законно сделала
   51 файл и два листа, и самопроверка стала красной, а проверка правил ушла
   в тихий пропуск, потому что стояла под `if (файлов CSS === 1)`. Тот же
   довод, по которому снято число `@media` (пункт 12 `docs/BACKLOG.md`):
   константа, которую двигают каждую сессию, перестаёт что-либо проверять,
   а проверка, которая молча не выполняется, хуже красной.

   Папка ниже создаётся ЭТИМ ЖЕ ТЕСТОМ во временном каталоге. Она не берётся
   из `dist/` и не зависит от состояния проекта — иначе мы повторили бы ту же
   ошибку в другом месте. Счётчик правил CSS при этом остаётся проверенным:
   ниже, на рукописном образце с заведомо известным устройством. */
{
  const корень = mkdtempSync(join(tmpdir(), 'accept-manifest-'));
  mkdirSync(join(корень, 'sub', 'deep'), { recursive: true });
  writeFileSync(join(корень, 'a.txt'), 'a');
  writeFileSync(join(корень, 'sub', 'b.txt'), 'bb');
  writeFileSync(join(корень, 'sub', 'deep', 'c.css'), 'ccc');

  const s = snapshot(корень);
  check('манифест: файлов на рукописной папке', 3, s.файлов, 'папка создана тестом: три файла на трёх уровнях');
  check(
    'манифест: пути и порядок',
    'a.txt,sub/b.txt,sub/deep/c.css',
    s.файлы.map((f) => f.file).join(','),
    'обход сортирован, разделитель приведён к косой черте'
  );
  check('манифест: размер в байтах', 2, s.файлы.find((f) => f.file === 'sub/b.txt').bytes, '«bb» — два байта');
  check(
    'манифест: sha256 известного содержимого',
    'ca978112ca1bbdcafac231b39a23dc4da786eff8147c4e72b9807785afee48bb',
    s.файлы[0].sha256,
    'sha256 строки «a» — величина внешняя, не из этого кода'
  );

  const сам = compare(s, snapshot(корень));
  check(
    'манифест: сверка себя с собой пуста',
    0,
    сам.добавлено.length + сам.удалено.length + сам.изменено.length,
    'те же байты — пустая диффа, иначе принимать нечем'
  );

  writeFileSync(join(корень, 'a.txt'), 'A');
  writeFileSync(join(корень, 'sub', 'new.txt'), 'n');
  rmSync(join(корень, 'sub', 'deep', 'c.css'));
  const после = compare(s, snapshot(корень));
  check('манифест: изменённый файл виден', 'a.txt', после.изменено.join(','), 'то же имя, другое содержимое');
  check('манифест: добавленный файл виден', 'sub/new.txt', после.добавлено.join(','), 'новое имя');
  check('манифест: удалённый файл виден', 'sub/deep/c.css', после.удалено.join(','), 'имя исчезло');

  rmSync(корень, { recursive: true, force: true });
}

/* — CSS живой сборки: счёт правил берётся со всех листов, сколько бы их
   ни было. Утверждения о ЧИСЛЕ правил здесь нет по доводу выше; печатается
   факт, а проверяется счётчик — ниже, на рукописном образце. */
const snap = snapshot(dist);
const cssFiles = readdirSync(join(dist, '_astro')).filter((f) => f.endsWith('.css'));
{
  const m = measure(cssFiles.map((f) => readFileSync(join(dist, '_astro', f), 'utf8')).join('\n'));
  console.log(`сборка: ${snap.файлов} файлов, листов ${cssFiles.length}, правил ${m.правил}, @media ${m.media_вхождений}`);
  console.log('');
}
// Число `@media`-блоков живой сборки здесь БОЛЬШЕ НЕ ПРОВЕРЯЕТСЯ, и это
// решение владельца от 2026-09-09 (пункт 12 `docs/BACKLOG.md`). Каждое
// расщепление законно разъединяет одноусловные медиаблоки — 22 → 24 → 26 → 27, —
// и константу приходилось двигать руками каждую сессию. Константа, которую
// двигают руками, перестаёт что-либо проверять. Взамен ниже стоит проверка
// самого счётчика на образце с известным устройством: она верна при любой
// сборке и ловит то единственное, что здесь и стоило ловить, — ошибку разбора.
// Тем же доводом 2026-09-09 сняты «файлов в dist/» и «правил CSS»: см. выше,
// проверку манифеста на рукописной папке.

/* — разметка: скруты находятся и приводятся к порядковому виду — */
const html = readFileSync(join(dist, 'index.html'), 'utf8');
const { map, html: normalized } = normalizeScopes(html);
check('скрутов в index.html', true, map.size > 0, 'вынос меняет data-astro-cid-*, значит они там есть');
check('после приведения скрутов не осталось исходных', true, !/data-astro-cid-[a-z0-9]{6,}\b/.test(normalized), 'нормализация');

/* — пиксели: знаменатель и чувствительность в один субпиксель — */
if (existsSync(baseline)) {
  const hero = readdirSync(baseline).find((f) => f.includes('desktop-hero'));
  if (hero) {
    const img = decodePng(readFileSync(join(baseline, hero)));
    const same = comparePixels(img, img);
    check('субпикселей в кадре 1440×900', 3888000, same.субпикселей, 'отчёты P2: «1 из 3 888 000»');
    check('кадр против себя даёт ноль различий', 0, same.различных, 'здравый смысл сравнения');

    // Один инвертированный субпиксель обязан быть найден: копия отличается
    // ровно на единицу в первом канале первого пикселя.
    const twin = { ...img, data: Buffer.from(img.data) };
    twin.data[0] = twin.data[0] ^ 0xff;
    const one = comparePixels(img, twin);
    check('один инвертированный субпиксель найден', 1, one.различных, 'отчёт 2026-09-07-p2-cta: «ловит один из 3 888 000»');
    check('рамка различий сжалась до одного пикселя', '1×1', `${one.рамка.ширина}×${one.рамка.высота}`, 'рамка');
  }
} else {
  cases.push({ имя: 'пиксельные проверки', ждём: '_baseline/', факт: 'нет папки', откуда: '', ok: false, пропуск: true });
}

/* — счётчик CSS на образце с известным устройством —
   Замена константе «@media-блоков» из живой сборки: та менялась каждым
   расщеплением, эта верна всегда. Образец написан руками, и в нём заведомо
   пять правил, два at-правила, три вхождения `@media` и два различных
   условия — включая два одноусловных блока подряд, то есть ровно тот случай,
   который расщепление и создаёт. */
{
  const образец = [
    '.a { color: red }',
    '@media (max-width: 10px) { .b { color: red } .c { color: red } }',
    '@media (max-width: 10px) { .d { color: red } }',
    '@media (max-width: 20px) { .e { color: red } }',
    "@property --x { syntax: '<color>'; inherits: false; initial-value: red }",
    '@font-face { font-family: X; src: url(x.woff2) }',
  ].join('\n');
  const о = measure(образец);
  check('счётчик: правил на образце', 5, о.правил, 'образец написан руками, счёт известен');
  check('счётчик: at-правил на образце', 2, о.at_правил, '@property и @font-face считаются отдельно');
  check('счётчик: вхождений @media', 3, о.media_вхождений, 'два одноусловных блока подряд — случай расщепления');
  check('счётчик: различных условий @media', 2, о.media_условий, 'одноусловные блоки не сливаются в счёте условий');
}

/* — плоское гашение: проверяются ИНВАРИАНТЫ режима, а не сегодняшние числа —
   Числа сборки для этой пары проверок не годятся: они меняются каждым
   расщеплением, а константа, которую двигают руками, ничего не проверяет.
   Поэтому здесь два утверждения, верных при любой сборке. */
{
  const образец = '<p class="a" data-astro-cid-abc12345>текст</p><i data-astro-cid-abc12345>i</i>';
  const { html: погашено, скрутов } = flattenScopes(образец);
  // Сравниваем с образцом, у которого заменён ТОЛЬКО хеш: если гашение тронет
  // хоть один другой байт, равенство не выполнится.
  check(
    'гашение стирает только хеш',
    true,
    погашено === образец.replaceAll('abc12345', '@'),
    'REUSE §6: «стирает только хеш и ничего больше»'
  );
  check('гашение считает различные скруты', 1, скрутов, 'счёт — компенсация за потерю различий');

  // Модель расщепления: один скрут файла становится тремя, причём скрут
  // обёртки уцелевает — он выводится из пути, а обёртка пути не меняет.
  const до = '<a data-astro-cid-aaaaaaaa></a><b data-astro-cid-aaaaaaaa></b><c data-astro-cid-aaaaaaaa></c>';
  const после = '<a data-astro-cid-aaaaaaaa></a><b data-astro-cid-bbbbbbbb></b><c data-astro-cid-cccccccc></c>';
  const л = scopeLedger(до, после);
  check('расщепление: скрутов 1 → 3', '1→3', `${л.до}→${л.после}`, 'REUSE §6, требование владельца П30 п.1');
  check('расщепление: скрут обёртки уцелел', 1, л.уцелели.length, 'скрут выводится из пути файла, а не из содержимого');
  check('расщепление: новых скрутов ровно два', 2, л.новые.length, 'иное число — остановка и разбор');
  check('расщепление: не исчез ни один', 0, л.ушли.length, 'исчезнувший скрут означает переезд файла, а не расщепление');
}

/* — предикат «нулевая витрина»: разбор на рукописных образцах —
   Числа здесь не из сборки, а из устройства: образцы написаны руками,
   и ответ известен заранее. Проверяется то, чем предикат отличает утилиту
   сканера от правила витрины, — на случаях, которые сессии и создают. */
{
  const SEP = '␟';
  const тройка = (усл, сел, объ) => [усл, сел, объ].join(SEP);

  check('витрина: селектор — один класс', 'underline', одинКласс('.underline'), 'утилита сканера всегда такова');
  check('витрина: скрут не класс', 'null', String(одинКласс('.layer__plate[data-astro-cid-@]')), 'правило витрины несёт скрут');
  check('витрина: составной селектор не класс', 'null', String(одинКласс('.a .b')), 'два класса — не утилита');
  check('витрина: экранированный класс читается', 'w-1/2', одинКласс('.w-1\\/2'), 'утилиты Tailwind несут / и : экранированными');

  check('витрина: слово целиком, не подстрока', false, словоЕсть('const blocks = []', 'block'), '`block` внутри `blocks` — не вхождение');
  check('витрина: слово находится', true, словоЕсть('{ block: string }', 'block'), 'имя поля контракта и есть источник утилиты');

  const образецHtml =
    '<html><head><link rel="stylesheet" href="/_astro/Base.CxtPq8QU.css">' +
    '<link rel="icon" href="/favicon.svg"><link rel="stylesheet" href="/_astro/index.Ck0Kjnc0.css">' +
    '</head><body><script src="/_astro/x.AbCdEfGh.js"></script></body></html>';
  const с = ссылки(образецHtml);
  check('витрина: ссылок в образце', 3, с.length, 'два листа и скрипт; favicon не лист и не считается');
  check('витрина: порядок ссылок', '/_astro/Base.ХЕШ.css', с[0], 'проверка 2 сторожит порядок, а не имена');

  const новые = new Map([['sites/x/src/lib/structure.ts', 'blocks: Array<{ block: string }>']]);
  const старые = new Map([['core/blocks/LinkColumns.astro', 'text-decoration: underline;']]);
  check(
    'витрина: утилита с нового файла принята',
    true,
    утилитаЛи(тройка('@layer components && @layer utilities', '.block', 'display:block'), новые, старые).да,
    'слово block стоит в новом файле'
  );
  check(
    'витрина: правило вне @layer utilities отклонено',
    false,
    утилитаЛи(тройка('@media (max-width: 640px)', '.block', 'display:block'), новые, старые).да,
    'утилиты сканера живут только в своём слое'
  );
  check(
    'витрина: неатрибутированная утилита отклонена',
    false,
    утилитаЛи(тройка('@layer utilities', '.underline', 'text-decoration-line:underline'), новые, старые).да,
    'слова нет ни в одном новом файле'
  );
  check(
    'витрина: слово в старом файле — не отказ',
    true,
    утилитаЛи(тройка('@layer utilities', '.block', 'display:block'), новые, старые).да,
    'измерено 2026-09-09: underline был в LinkColumns, а утилиты не было'
  );
}

/* — вывод — */
let failed = 0;
for (const c of cases) {
  if (!c.ok && !c.пропуск) failed += 1;
  const mark = c.пропуск ? 'нет ' : c.ok ? 'ok  ' : 'ЗЛЕ ';
  console.log(`${mark} ${String(c.имя).padEnd(44)} ждём ${String(c.ждём).padEnd(9)} факт ${String(c.факт).padEnd(9)} ${c.откуда}`);
}
console.log('');
console.log(`${cases.filter((c) => c.ok).length}/${cases.length} чисел воспроизведены из записей прошлых сессий`);
if (failed) {
  console.error('');
  console.error('Расхождение с записью. Разошлись либо инструмент, либо сборка — разбираться до того,');
  console.error('как этим инструментом начнут принимать выносы.');
  process.exit(1);
}

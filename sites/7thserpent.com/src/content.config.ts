import { defineCollection } from 'astro:content';
import { glob } from 'astro/loaders';
import { z } from 'zod';

/**
 * Содержание страниц дерева (пачка 0, П85 п. 1) — форма схемы первого сайта
 * (`sites/ac4bf-thewatch.com/src/content.config.ts`), написанная заново в LF;
 * вынос в ядро — позже.
 *
 * ПОЛЯ SEO ЗДЕСЬ НЕ ЖИВУТ. `title`, `h1`, `description`, `keywords`, `parent`
 * и сами ссылки `related` — только в `structure.json` (П24 п. 3); здесь у
 * `related` — только заголовок секции. Схема — место, где это
 * правило перестаёт быть договорённостью и становится ошибкой сборки.
 *
 * СХЕМА СТРОГАЯ — `.strict()` у каждого объекта (бэклог 44, П52 п. 5):
 * неизвестный ключ — прерванная сборка с именем файла и ключа, а не тихо
 * отрезанное поле. Литеральная опечатка в имени поля блока иначе исчезала бы
 * вместе с полем.
 *
 * ПОЛЯ — ТОЛЬКО У ВЕТВЕЙ, КОТОРЫЕ МАРШРУТ ПЕЧАТАЕТ. Маршрут печатает пять
 * блоков — `story-row` и `link-list` (пачка 0, стенд `/404/`, П85 п. 6),
 * `cta-band` (пачка 1, П89: `/pc/`, `/games-like-max-payne/`, `/media/`),
 * `hero-key-art` и `byline` (пачка 2, П91: `/max-payne-1/`, `/max-payne-2/`,
 * `/max-payne-3/`, `/remake/`); ряд — с кадром или без (кадр ряда — пачка 1,
 * ответ владельца 2 в П89). Поля остальных блоков дерева (`gallery`)
 * приходят в схему вместе с их ветвью маршрута и первой страницей формы
 * (план P4, доклад сессии 12). Поле, которого никто не печатает, — тихая
 * заглушка: схема его не примет, а маршрут откажет на блоке без ветви.
 *
 * Какой блок и в каком порядке — говорит `blocks[]` структуры; чем его
 * наполнить — этот файл. Вторую сторону договора — поле блока, которого
 * страница не объявляет, — сторожит маршрут (`POLE_BLOKA` в `[...slug].astro`):
 * здесь видна только форма поля, там — есть ли блок.
 */

/**
 * Строка текста: пустая или из пробельных символов (пробел, таб, неразрывный,
 * BOM) — отказ («судью судят», раунд 1, R1-MARSHRUT-1, -4). Пустой заголовок
 * `related` уводил `link-list` ядра в голую ветку без секции и заголовка,
 * пустые `year`, `title`, `meta` и абзацы печатали пустые элементы — тихие
 * заглушки без отказа. Края строки срезаются.
 * Пределы (раунд 2): невидимые знаки вне класса пробельных (U+200B, мягкий
 * перенос, U+2060, U+180E) проходят и печатают «пустой» элемент (R2-MARSHRUT-3;
 * с пачки 2 — и у полей героя и подписи, P2-R1-MARSHRUT-8); ряд
 * без надзаголовка или меты невыразим — `year` и `meta` обязательны, как у
 * первого сайта; решение — с первой страницей, где ряду они не нужны
 * (`/privacy/`, публикация) (R2-MARSHRUT-5).
 */
const tekst = () => z.string().trim().min(1);

/** Ключ кадра — ключ разрешателя `kadr()` (`src/data/media.ts`): файл
 *  `src/assets/gry/<ключ>.jpg` и запись `game-art.json`. Ключ без файла или
 *  записи — прерванная сборка в `kadr()`, не пустая рамка. */
const klyuchKadra = () => z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/);

/**
 * Кнопка героя (пачка 2, П91) — форма первого сайта (`link`: `href`, `label`).
 * `href` — якорь раздела этой страницы (`#id` ряда, kebab) или адрес от корня
 * сайта; адрес от корня не начинается с `//` или `/\` (браузер увёл бы такой
 * адрес на чужой хост — тот же запрет, что у `cta.href`, R1-MARSHRUT-1 пачки 1),
 * пробелов и `#` в нём нет: якорь на ДРУГОЙ странице (`/max-payne-1/#where`)
 * не судит никто — `anchors` смотрит только адреса из одного `#…`, `links`
 * отрезает фрагмент («судью судят», раунд 1, P2-R1-MARSHRUT-7). Внешних адресов
 * у кнопок героя нет: первый экран ведёт внутрь сайта. Что якорь есть на
 * странице, судит сторож `anchors` после сборки, что адрес есть в структуре —
 * сторож `links`.
 */
const knopka = () =>
  z
    .object({
      href: z.string().regex(/^(?:#[a-z0-9]+(?:-[a-z0-9]+)*|\/(?![/\\])[^\s#]*)$/),
      label: tekst(),
    })
    .strict();

export const collections = {
  tresc: defineCollection({
    // Id записи — путь файла, а не слаг: по слагу Astro сливает `404.md`
    // и `404/index.md` в одну запись с предупреждением, и проверка «два файла
    // на один адрес» маршрута дубля не видела (раунд 1, R1-MARSHRUT-3).
    // Предел (раунд 2, R2-MARSHRUT-4): шаблон — `*.md` строчными; файл `.MD`
    // или `.markdown` в коллекцию молча не попадает, и страница не собирается.
    loader: glob({ pattern: '**/*.md', base: './src/content/tresc', generateId: ({ entry }) => entry }),
    schema: z
      .object({
        url: z.string().startsWith('/').endsWith('/'),

        /* — hero-key-art (пачка 2, П91) — поля первого сайта: `lead`, `primary`,
           `secondary`, `art`. Все четыре — необязательны для схемы и обязательны
           разом для героя: страница, объявившая `hero-key-art` без полного набора,
           не собирается, и отказ называет поле (маршрут). `art` обязателен у героя
           этого сайта — запасной графики нет, п. 4 П91 называет арт каждой
           страницы. `artFocus` — кадровка арта (`object-position`: «x% y%»),
           нет поля — середина кадра. `artCaption` — подпись кадра, когда на нём
           не игра страницы (`/remake/`: кадр оригинала, П91 п. 4–5); печатается
           местом `dopisek` героя ядра, ролью `.t-caption` (маршрут). */
        art: klyuchKadra().optional(),
        artFocus: z.string().regex(/^(?:100|[1-9]?\d)% (?:100|[1-9]?\d)%$/).optional(),
        artCaption: tekst().optional(),
        lead: tekst().optional(),
        primary: knopka().optional(),
        secondary: knopka().optional(),

        /* — byline (пачка 2, П91) — поля первого сайта. `date` — машинная дата
           для `<time datetime>`: календарная дата ГГГГ-ММ-ДД (31 февраля — отказ),
           не раньше 2000 года и не позже дня сборки; `dateLabel` — та же дата
           словами, ровно так, как её пишет американский английский («September
           26, 2026»), — иначе машинная и видимая даты расходились бы без отказа
           («судью судят», раунд 1, P2-R1-MARSHRUT-4); `role` — приписка перед
           автором. */
        byline: z
          .object({
            author: tekst(),
            date: z
              .string()
              .regex(/^\d{4}-\d{2}-\d{2}$/)
              .refine((s) => {
                const d = new Date(`${s}T00:00:00Z`);
                return !Number.isNaN(d.getTime()) && d.toISOString().slice(0, 10) === s;
              }, 'не календарная дата'),
            dateLabel: tekst(),
            role: tekst().optional(),
          })
          .strict()
          .superRefine((b, ctx) => {
            const d = new Date(`${b.date}T00:00:00Z`);
            if (Number.isNaN(d.getTime())) return;
            if (d.getUTCFullYear() < 2000) ctx.addIssue({ code: 'custom', path: ['date'], message: 'дата подписи раньше 2000 года' });
            if (d.getTime() > Date.now()) ctx.addIssue({ code: 'custom', path: ['date'], message: 'дата подписи позже дня сборки' });
            const slovami = new Intl.DateTimeFormat('en-US', { month: 'long', day: 'numeric', year: 'numeric', timeZone: 'UTC' }).format(d);
            if (b.dateLabel !== slovami) ctx.addIssue({ code: 'custom', path: ['dateLabel'], message: `не та же дата словами: ждали «${slovami}»` });
          })
          .optional(),

        /* — story-row, по записи на ряд —
           `role` — вхождение блока с ролью (`story-row#mobile` на `/max-payne-1/`,
           `story-row#max-payne-4` на `/remake/`): ряд без роли печатается
           вхождением без роли, ряд с ролью — вхождением с той же ролью
           (маршрут, `ROLE_UMIE`). Ряд с ролью, которой страница не объявляет, —
           отказ маршрута, не тихий пропуск. */
        rows: z
          .array(
            z
              .object({
                id: z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/),
                role: z.string().min(1).optional(),
                /** Надзаголовок ряда — роль `t-label` (у сайта нет `t-year`
                 *  первого сайта; ярлык — капслок гротеска, как год у узла трассы). */
                year: tekst(),
                title: tekst(),
                meta: tekst(),
                body: z.array(tekst()).nonempty(),
                /** Кадр ряда — ключ разрешателя `kadr()` (`klyuchKadra` выше).
                 *  Нет поля — ряд в один столбец (П44). */
                art: klyuchKadra().optional(),
                flip: z.boolean().default(false),
                band: z.boolean().default(false),
              })
              .strict()
          )
          .default([]),

        /* — link-list: заголовок секции; сами ссылки — `related` структуры — */
        related: z.object({ title: tekst() }).strict().optional(),

        /* — cta-band: полоса призыва, форма первого сайта (П89 п. 1 «Как прочитано»).
           `href` — адрес от корня сайта или внешний `https://` с хостом
           (официальный канал издателя — П89 п. 5); пробелов в адресе нет.
           Адрес от корня не начинается с `//` или `/\`: браузер уводит такой
           адрес на чужой хост, а сторож `links` принял бы `/\host/` за главную
           («судью судят», раунд 1, R1-MARSHRUT-1). Что адрес от корня есть
           в структуре, судит сторож `links` после сборки; страница по нему
           может быть ещё не собрана (плановый адрес дерева законен). У внешнего
           адреса хост — непустой, без `/ \ ? # @ : %`, затем порт и путь
           (раунд 2, R2-MARSHRUT-1: `https://?x` проходил схему). Какой хост,
           схема не судит (`https://.` пройдёт — мёртвая ссылка). Арта у призыва
           маршрута нет (П89, слова владельца, п. 3). */
        cta: z
          .object({
            title: tekst(),
            lead: tekst(),
            href: z.string().regex(/^(?:\/(?![/\\])\S*|https:\/\/[^/\\\s?#@:%]+(?::\d+)?(?:[/?#]\S*)?)$/),
            label: tekst(),
          })
          .strict()
          .optional(),
      })
      .strict(),
  }),
};

import { defineCollection } from 'astro:content';
import { glob } from 'astro/loaders';
import { z } from 'zod';

/**
 * Содержание страниц дерева (пачка 0, П85 п. 1) — форма схемы первого сайта
 * (`sites/ac4bf-thewatch.com/src/content.config.ts`), написанная заново в LF;
 * вынос в ядро — позже.
 *
 * ПОЛЯ SEO ЗДЕСЬ НЕ ЖИВУТ. `title`, `h1`, `description`, `keywords`, `parent`
 * и сами ссылки `related` — только в `structure.json` (П24 п. 3); здесь у
 * `related` — только заголовок секции. Схема — место, где это
 * правило перестаёт быть договорённостью и становится ошибкой сборки.
 *
 * СХЕМА СТРОГАЯ — `.strict()` у каждого объекта (бэклог 44, П52 п. 5):
 * неизвестный ключ — прерванная сборка с именем файла и ключа, а не тихо
 * отрезанное поле. Литеральная опечатка в имени поля блока иначе исчезала бы
 * вместе с полем.
 *
 * ПОЛЯ — ТОЛЬКО У ВЕТВЕЙ, КОТОРЫЕ МАРШРУТ ПЕЧАТАЕТ. Маршрут пачки 0 печатает
 * два блока — `story-row` и `link-list` (стенд `/404/`, П85 п. 6); поля
 * остальных блоков дерева (`hero-key-art`, `byline`, `gallery`, `cta-band`)
 * приходят в схему вместе с их ветвью маршрута и первой страницей формы
 * (план P4, доклад сессии 12). Поле, которого никто не печатает, — тихая
 * заглушка: схема его не примет, а маршрут откажет на блоке без ветви.
 *
 * Какой блок и в каком порядке — говорит `blocks[]` структуры; чем его
 * наполнить — этот файл. Вторую сторону договора — поле блока, которого
 * страница не объявляет, — сторожит маршрут (`POLE_BLOKA` в `[...slug].astro`):
 * здесь видна только форма поля, там — есть ли блок.
 */

/**
 * Строка текста: пустая или из пробельных символов (пробел, таб, неразрывный,
 * BOM) — отказ («судью судят», раунд 1, R1-MARSHRUT-1, -4). Пустой заголовок
 * `related` уводил `link-list` ядра в голую ветку без секции и заголовка,
 * пустые `year`, `title`, `meta` и абзацы печатали пустые элементы — тихие
 * заглушки без отказа. Края строки срезаются.
 * Пределы (раунд 2): невидимые знаки вне класса пробельных (U+200B, мягкий
 * перенос, U+2060) проходят и печатают «пустой» элемент (R2-MARSHRUT-3); ряд
 * без надзаголовка или меты невыразим — `year` и `meta` обязательны, как у
 * первого сайта; решение — с первой страницей, где ряду они не нужны
 * (`/privacy/`, публикация) (R2-MARSHRUT-5).
 */
const tekst = () => z.string().trim().min(1);

export const collections = {
  tresc: defineCollection({
    // Id записи — путь файла, а не слаг: по слагу Astro сливает `404.md`
    // и `404/index.md` в одну запись с предупреждением, и проверка «два файла
    // на один адрес» маршрута дубля не видела (раунд 1, R1-MARSHRUT-3).
    // Предел (раунд 2, R2-MARSHRUT-4): шаблон — `*.md` строчными; файл `.MD`
    // или `.markdown` в коллекцию молча не попадает, и страница не собирается.
    loader: glob({ pattern: '**/*.md', base: './src/content/tresc', generateId: ({ entry }) => entry }),
    schema: z
      .object({
        url: z.string().startsWith('/').endsWith('/'),

        /* — story-row, по записи на ряд —
           `role` — вхождение блока с ролью (`story-row#mobile` на `/max-payne-1/`,
           `story-row#max-payne-4` на `/remake/`): ряд без роли печатается
           вхождением без роли, ряд с ролью — вхождением с той же ролью
           (маршрут, `ROLE_UMIE`). Ряд с ролью, которой страница не объявляет, —
           отказ маршрута, не тихий пропуск. */
        rows: z
          .array(
            z
              .object({
                id: z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/),
                role: z.string().min(1).optional(),
                /** Надзаголовок ряда — роль `t-label` (у сайта нет `t-year`
                 *  первого сайта; ярлык — капслок гротеска, как год у узла трассы). */
                year: tekst(),
                title: tekst(),
                meta: tekst(),
                body: z.array(tekst()).nonempty(),
                flip: z.boolean().default(false),
                band: z.boolean().default(false),
              })
              .strict()
          )
          .default([]),

        /* — link-list: заголовок секции; сами ссылки — `related` структуры — */
        related: z.object({ title: tekst() }).strict().optional(),
      })
      .strict(),
  }),
};

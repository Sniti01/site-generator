#!/usr/bin/env node
/**
 * Приёмка: допуск шума — числом, не прозой (П45, 2026-09-12).
 *
 *   node core/accept/szum.mjs <снятые> <эталон>   — каждый кадр эталона против снятого по зонам `<эталон>/szum.json`
 *
 * **«Допуск без числа в коде — не допуск, а привычка»** — решение владельца
 * П45. До этого дня зоны шума жили прозой в `_baseline/README.md`
 * («Зоны шума — известные не-судьи внутри кадров»), `frames.mjs check`
 * сверял состав, размеры и геометрию, а пиксели сверялись руками через
 * `pixels.mjs` — без порога, приговор выносил человек. Теперь рядом
 * с эталоном лежит `szum.json`: список зон, у каждой — какие кадры, рамка
 * (или весь кадр), маска «только светлые пиксели эталона» с порогом яркости
 * и амплитуда `макс` из 255. Правило одно, и оно здесь в коде:
 *
 *   каждый различающийся субпиксель обязан попасть в какую-то зону — имя
 *   кадра подходит под `кадры`, точка внутри `рамка` (или рамка `null`),
 *   для `только_светлые` яркость ЭТАЛОННОГО пикселя ≥ `порог_яркости` —
 *   И |Δ| ≤ `макс` этой зоны; иначе субпиксель ВНЕ ДОПУСКА, кадр — отказ.
 *
 * Размеры разошлись — вне допуска целиком: сравнивать нечего, и высота
 * полного кадра — находка сама по себе (`MIGRATION.md` §6). Нет `szum.json` —
 * зон нет, любой дифф — отказ: молчание файла не даёт допуска.
 *
 * Меряется так же, как в `pixels.mjs`: три канала на пиксель, альфа не
 * в счёт, субпиксели. Яркость пикселя — `max(R, G, B)` эталона, 0–255
 * (`ЯРКОСТЬ`). Рамка — полуоткрытая, как `getBoundingClientRect`: пиксель
 * внутри при `x ≤ px < x + w` и `y ≤ py < y + h`; полоса шкалы `x: 37, w: 10`
 * покрывает столбцы 37…46, столбец 47 снаружи (измерено 2026-09-12 по нулевому
 * прогону: рамки различий 8×414 от (38, 61) и 10×156 от (37, 61)).
 *
 * Чистая функция `ocenSzum` принимает **разобранные** кадры
 * (`{ width, height, channels, data }` из `decodePng`), CLI и `frames.mjs check`
 * декодируют сами; батарея `selftest.mjs` кормит её синтетическими кадрами
 * без PNG. Код возврата CLI: 1 при любом кадре вне допуска (в том числе
 * не снятом), 2 — инструмент не смог (нет папки, эталон без единого PNG,
 * битый PNG, негодный `szum.json` или `ne-sudyi.json`).
 *
 * **«В допуске» печатается по первой принявшей зоне** в порядке списка:
 * субпиксель, который приняли бы две зоны, записан за первой, и счётчики
 * зон — не независимые меры, а разложение одного диффа по порядку файла.
 * Зона с меньшим `макс` следующую не заслоняет: субпиксель ищет дальше.
 *
 * **Не-судьи** (`ne-sudyi.json` эталона) сверяются, но не судятся: строка
 * «НЕ СУДЬЯ … пиксели не судятся: N различий», отдельная графа `не судей`
 * в итоге, в код возврата не идёт. Что значит не-судья при кодовом вердикте —
 * вопрос владельцу. **Лишний** снятый кадр (нет в эталоне) — строка
 * «ЛИШНИЙ», не отказ, но не молчание.
 */

import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join, sep } from 'node:path';
import { decodePng } from './pixels.mjs';

/** Яркость пикселя для маски «только светлые»: max(R, G, B), 0–255. */
export const ЯРКОСТЬ = (r, g, b) => Math.max(r, g, b);

const целое = (v, от, до) => Number.isInteger(v) && v >= от && v <= до;
const КАНАЛ = ['R', 'G', 'B'];

/**
 * Проверка формы зон: каждая дыра в данных — отказ с именем зоны и поля,
 * а не молчаливый пропуск (зона с опечаткой в рамке, которая «ничего
 * не покрывает», хуже отсутствующей). Возвращает тот же список.
 */
export function проверитьЗоны(зоны) {
  if (!Array.isArray(зоны)) throw new Error('szum: список зон — не массив');
  const имена = new Set();
  зоны.forEach((з, i) => {
    const кто = `szum: зона №${i + 1}${з && typeof з.зона === 'string' ? ` («${з.зона}»)` : ''}`;
    if (!з || typeof з !== 'object') throw new Error(`${кто}: не объект`);
    if (typeof з.зона !== 'string' || !з.зона) throw new Error(`${кто}: поле «зона» — непустая строка`);
    if (имена.has(з.зона)) throw new Error(`${кто}: имя зоны повторяется`);
    имена.add(з.зона);
    if (typeof з.кадры === 'string') {
      // Пустая строка — `new RegExp('')` подходит любому кадру молча: отказ, не «все кадры».
      if (!з.кадры) throw new Error(`${кто}: «кадры» — пустая строка подошла бы любому кадру; назови кадры`);
      try { new RegExp(з.кадры); } catch (e) { throw new Error(`${кто}: «кадры» — негодное регулярное выражение: ${e.message}`); }
    } else if (!Array.isArray(з.кадры) || !з.кадры.length || !з.кадры.every((k) => typeof k === 'string' && k)) {
      throw new Error(`${кто}: «кадры» — регулярное выражение строкой или непустой список имён файлов`);
    }
    if (з.рамка !== null) {
      const р = з.рамка;
      if (!р || typeof р !== 'object' || !целое(р.x, 0, 1e6) || !целое(р.y, 0, 1e6) || !целое(р.w, 1, 1e6) || !целое(р.h, 1, 1e6)) {
        throw new Error(`${кто}: «рамка» — null (весь кадр) или { x, y, w, h } целыми, w и h ≥ 1`);
      }
    }
    if (typeof з.только_светлые !== 'boolean') throw new Error(`${кто}: «только_светлые» — true или false`);
    if (з.только_светлые && !целое(з.порог_яркости, 0, 255)) throw new Error(`${кто}: при «только_светлые» нужен «порог_яркости» 0–255`);
    if (!целое(з.макс, 1, 255)) throw new Error(`${кто}: «макс» — целое 1–255`);
  });
  return зоны;
}

/** Подходит ли зона кадру по имени: строка — регулярное выражение, список — точные имена. */
export const подходитКадр = (зона, nazwa) =>
  typeof зона.кадры === 'string' ? new RegExp(зона.кадры).test(nazwa) : зона.кадры.includes(nazwa);

/**
 * Читает `<папка>/szum.json`. Нет файла — `{ зоны: [], файл: null }`: зон нет,
 * любой дифф — отказ. Есть, но негоден — бросает: инструмент не смог.
 */
export function читатьЗоны(папка) {
  const файл = join(папка, 'szum.json');
  if (!existsSync(файл)) return { зоны: [], файл: null };
  let данные;
  try {
    данные = JSON.parse(readFileSync(файл, 'utf8'));
  } catch (e) {
    throw new Error(`szum: ${файл} не читается: ${e.message}`);
  }
  if (!данные || !Array.isArray(данные.зоны)) throw new Error(`szum: ${файл}: нет списка «зоны»`);
  return { зоны: проверитьЗоны(данные.зоны), файл };
}

/**
 * Сверка одного кадра по зонам. `etalon`, `snyate` — разобранные кадры;
 * `zony` — список зон (форма — `проверитьЗоны`); `nazwa` — имя файла кадра.
 *
 * Возвращает `{ размеры: 'равны' | 'разошлись', различных, макс,
 *   в_допуске: [{ зона, субпикселей, макс }],
 *   вне_допуска: null | { субпикселей, макс, рамка { x, y, w, h },
 *                         первый { x, y, канал, было, стало } } }`.
 * При разошедшихся размерах: `различных`/`макс` — null, `было`/`стало` —
 * размеры, `вне_допуска.причина` — словами.
 *
 * Различающийся субпиксель отдаётся первой по списку зоне, которая его
 * принимает (кадр, рамка, яркость, амплитуда); зона, которая «почти
 * принимает» (та же рамка, но амплитуда меньше), пропускается — субпиксель
 * ищет дальше и, не найдя, идёт вне допуска.
 */
export function ocenSzum({ etalon, snyate, zony = [], nazwa }) {
  if (typeof nazwa !== 'string' || !nazwa) throw new Error('ocenSzum: нет имени кадра — зоны выбираются по имени');
  const зоны = проверитьЗоны(zony);
  for (const к of [etalon, snyate]) {
    if (!к || !целое(к.width, 1, 1e6) || !целое(к.height, 1, 1e6) || !(к.channels === 3 || к.channels === 4) || !к.data) {
      throw new Error(`ocenSzum(${nazwa}): кадр не разобран — ожидались { width, height, channels 3|4, data }`);
    }
    if (к.data.length < к.width * к.height * к.channels) throw new Error(`ocenSzum(${nazwa}): данных меньше, чем width × height × channels`);
  }
  if (etalon.width !== snyate.width || etalon.height !== snyate.height) {
    const было = [etalon.width, etalon.height];
    const стало = [snyate.width, snyate.height];
    return {
      размеры: 'разошлись', было, стало, различных: null, макс: null, в_допуске: [],
      вне_допуска: { причина: `размеры разошлись: эталон ${было.join('×')}, снято ${стало.join('×')} — сравнивать нечего`, субпикселей: null, макс: null, рамка: null, первый: null },
    };
  }

  const свои = зоны.filter((з) => подходитКадр(з, nazwa));
  const { width, height } = etalon;
  const ca = etalon.channels;
  const cb = snyate.channels;
  const A = etalon.data;
  const B = snyate.data;
  let различных = 0;
  let макс = 0;
  const поЗонам = new Map();
  let вне = null;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const ia = (y * width + x) * ca;
      const ib = (y * width + x) * cb;
      if (A[ia] === B[ib] && A[ia + 1] === B[ib + 1] && A[ia + 2] === B[ib + 2]) continue;
      const яркость = ЯРКОСТЬ(A[ia], A[ia + 1], A[ia + 2]);
      for (let k = 0; k < 3; k++) {
        const d = Math.abs(A[ia + k] - B[ib + k]);
        if (d === 0) continue;
        различных += 1;
        if (d > макс) макс = d;
        let зона = null;
        for (const з of свои) {
          const р = з.рамка;
          if (р && !(x >= р.x && x < р.x + р.w && y >= р.y && y < р.y + р.h)) continue;
          if (з.только_светлые && яркость < з.порог_яркости) continue;
          if (d > з.макс) continue;
          зона = з;
          break;
        }
        if (зона) {
          const с = поЗонам.get(зона.зона) ?? { зона: зона.зона, субпикселей: 0, макс: 0 };
          с.субпикселей += 1;
          if (d > с.макс) с.макс = d;
          поЗонам.set(зона.зона, с);
        } else if (вне) {
          вне.субпикселей += 1;
          if (d > вне.макс) вне.макс = d;
          if (x < вне.x0) вне.x0 = x;
          if (x > вне.x1) вне.x1 = x;
          if (y < вне.y0) вне.y0 = y;
          if (y > вне.y1) вне.y1 = y;
        } else {
          вне = { субпикселей: 1, макс: d, x0: x, x1: x, y0: y, y1: y, первый: { x, y, канал: КАНАЛ[k], было: A[ia + k], стало: B[ib + k] } };
        }
      }
    }
  }
  return {
    размеры: 'равны',
    различных,
    макс,
    в_допуске: свои.filter((з) => поЗонам.has(з.зона)).map((з) => поЗонам.get(з.зона)),
    вне_допуска: вне
      ? { субпикселей: вне.субпикселей, макс: вне.макс, рамка: { x: вне.x0, y: вне.y0, w: вне.x1 - вне.x0 + 1, h: вне.y1 - вне.y0 + 1 }, первый: вне.первый }
      : null,
  };
}

/** Вердикт одного кадра одной строкой — общая для CLI и `frames.mjs check`. */
export function строкаВердикта(r, nazwa) {
  if (r.размеры === 'разошлись') return `ВНЕ ДОПУСКА  ${nazwa}: ${r.вне_допуска.причина}`;
  const вД = r.в_допуске.map((з) => `зона ${з.зона} — ${з.субпикселей} (макс ${з.макс})`).join(', ');
  if (!r.вне_допуска) return r.различных === 0 ? `0 различий   ${nazwa}` : `в допуске    ${nazwa}: ${вД}`;
  const v = r.вне_допуска;
  return `ВНЕ ДОПУСКА  ${nazwa}: ${v.субпикселей} субпикселей, макс ${v.макс}, рамка ${v.рамка.w}×${v.рамка.h} от (${v.рамка.x}, ${v.рамка.y}), первый (${v.первый.x}, ${v.первый.y}) ${v.первый.канал} ${v.первый.было}→${v.первый.стало}${вД ? `; в допуске: ${вД}` : ''}`;
}

/** Строка про отсутствие зон или их число — печатается перед сверкой. */
export const строкаЗон = ({ зоны, файл }) =>
  файл ? `ЗОНЫ ШУМА: ${файл} — зон ${зоны.length}; каждый субпиксель вне зон или выше её «макс» — отказ.` : 'ЗОНЫ ШУМА: szum.json нет — зон нет: любой дифф — отказ.';

/** Зоны, не подошедшие ни к одному кадру эталона, — названы: опечатка в «кадры» молчала бы. */
export const зоныБезКадров = (зоны, кадры) => зоны.filter((з) => !кадры.some((к) => подходитКадр(з, к))).map((з) => з.зона);

/**
 * Читает `<папка>/ne-sudyi.json` — кадры, временно не являющиеся судьями
 * (решение владельца 2026-09-09, список ведётся рядом с эталоном). Нет файла —
 * судьи все; есть, но не читается — бросает: инструмент не смог, а не «судьи все».
 */
export function читатьНеСудей(папка) {
  const файл = join(папка, 'ne-sudyi.json');
  if (!existsSync(файл)) return { кадры: [], файл: null };
  let данные;
  try {
    данные = JSON.parse(readFileSync(файл, 'utf8'));
  } catch (e) {
    throw new Error(`ne-sudyi: ${файл} не читается: ${e.message}`);
  }
  const кадры = Array.isArray(данные?.кадры) ? данные.кадры : [];
  if (!кадры.every((к) => к && typeof к.кадр === 'string' && к.кадр)) throw new Error(`ne-sudyi: ${файл}: у каждой записи «кадры» нужно поле «кадр» с именем файла`);
  return { кадры, файл };
}

/** Строка не-судьи: пиксели посчитаны, но не судятся — число печатается, в код возврата не идёт. */
export function строкаНеСудьи(r, nazwa) {
  const что = !r ? 'не снят' : r.размеры === 'разошлись' ? r.вне_допуска.причина : `${r.различных} различий${r.различных ? `, макс ${r.макс}` : ''}`;
  return `НЕ СУДЬЯ     ${nazwa} — пиксели не судятся: ${что}`;
}

/**
 * Счёт по списку вердиктов `{ nazwa, r | null, неСудья? }` (`r` null — кадр
 * не снят). Не-судья считается своей графой `не_судей` — ни в «вне допуска»,
 * ни в код возврата; что значит не-судья при кодовом вердикте — вопрос владельцу.
 */
export function итог(вердикты) {
  const с = { кадров: вердикты.length, чистых: 0, вДопуске: 0, внеДопуска: 0, не_судей: 0 };
  for (const { r, неСудья } of вердикты) {
    if (неСудья) с.не_судей += 1;
    else if (!r || r.вне_допуска) с.внеДопуска += 1;
    else if (r.различных === 0) с.чистых += 1;
    else с.вДопуске += 1;
  }
  return с;
}

export const строкаИтога = (с) => `ИТОГ ПИКСЕЛЕЙ: кадров ${с.кадров} — 0 различий ${с.чистых}, в допуске ${с.вДопуске}, вне допуска ${с.внеДопуска}${с.не_судей ? `, не судей ${с.не_судей}` : ''}${с.внеДопуска ? ' — ОТКАЗ' : ''}.`;

/** Кадры, которые есть в снятом, но не в эталоне, — названы: кадр без судьи не отказ, но и не молчание. */
export const лишние = (base, got) => [...got].filter((f) => !base.includes(f)).sort();

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split(sep).join('/'))) {
  const [, , снятые, эталон] = process.argv;
  if (!снятые || !эталон) {
    console.error('node core/accept/szum.mjs <снятые> <эталон>');
    process.exit(2);
  }
  if (!existsSync(снятые) || !existsSync(эталон)) {
    console.error('нет папки с кадрами');
    process.exit(2);
  }
  const base = readdirSync(эталон).filter((f) => f.endsWith('.png')).sort();
  if (!base.length) {
    console.error(`в эталоне ${эталон} нет ни одного .png — сверять нечего (опечатка в пути?)`);
    process.exit(2);
  }
  const got = new Set(readdirSync(снятые).filter((f) => f.endsWith('.png')));
  let зоны;
  let неСудьи;
  try {
    зоны = читатьЗоны(эталон);
    неСудьи = читатьНеСудей(эталон);
  } catch (e) {
    console.error(e.message);
    process.exit(2);
  }
  const неСудья = new Set(неСудьи.кадры.map((к) => к.кадр));
  console.log(строкаЗон(зоны));
  for (const з of зоныБезКадров(зоны.зоны, base)) console.log(`  зона ${з} не подошла ни к одному кадру эталона — проверь «кадры».`);
  const вердикты = [];
  for (const nazwa of base) {
    const путь = join(снятые, nazwa);
    let r = null;
    if (existsSync(путь)) {
      try {
        r = ocenSzum({ etalon: decodePng(readFileSync(join(эталон, nazwa))), snyate: decodePng(readFileSync(путь)), zony: зоны.зоны, nazwa });
      } catch (e) {
        console.error(`${nazwa}: ${e.message}`);
        process.exit(2);
      }
    }
    if (неСудья.has(nazwa)) {
      console.log(`  ${строкаНеСудьи(r, nazwa)}`);
      вердикты.push({ nazwa, r, неСудья: true });
    } else {
      console.log(`  ${r ? строкаВердикта(r, nazwa) : `ВНЕ ДОПУСКА  ${nazwa}: не снят`}`);
      вердикты.push({ nazwa, r });
    }
  }
  for (const f of лишние(base, got)) console.log(`  ЛИШНИЙ       ${f} — есть в снятом, нет в эталоне: кадр без судьи`);
  const с = итог(вердикты);
  console.log(строкаИтога(с));
  process.exit(с.внеДопуска ? 1 : 0);
}

#!/usr/bin/env node
/**
 * Приёмка: строчные польские диакритики отрисовываются строчными глифами.
 *
 *   node core/accept/glyphs.mjs protocol
 *   node core/accept/glyphs.mjs check <ячейки.json> <кадр.png>
 *
 * **Повод.** `Cinzel` — капитель, и восемь её строчных польских букв
 * (`ą ć ę ł ń ś ź ż`) нарисованы ПРОПИСНЫМИ глифами; верна одна `ó`. Роли
 * `t-title` и `t-year` печатали ими живой текст, и на польском сайте стояло
 * «DziewiĘĆ celów Al Mualima — kolejnoŚĆ». Дефект прожил три фазы в принятом
 * эталоне: побайтовый ноль обещает воспроизводимость, а не правильность.
 *
 * ## Чем НЕ надо это мерить — три меры перепробованы и негодны
 *
 * Все три проверены 2026-09-09 на двух гарнитурах сайта. Не переписывайте
 * проверку на них как на более простое.
 *
 * 1. **Ширина знака.** Ложно обвиняет Manrope в `ę` и `ś` и пропускает
 *    сломанные `ą ę ś` в Cinzel.
 * 2. **Полная высота чернил.** У сломанных букв Cinzel даёт 14–15 px разницы
 *    с прописной вместо нуля: строчная нарисована прописной формой, но акут
 *    у неё посажен ниже. Разделения нет.
 * 3. **Любой счёт на `<canvas>`.** Канва рисует НЕ ТО ЖЕ, что DOM: базовые
 *    буквы берёт из веб-шрифта, а знаки с диакритикой — из запасного.
 *    Измерено: на заведомо сломанном Cinzel канва дала `тело(ć) = 99`
 *    при `c = 99` и `C = 142`, то есть «чисто». Канва здесь лжёт.
 *
 * ## Чем мерить
 *
 * Отрисовкой в DOM, снимком и разбором растра — тем единственным способом,
 * которым дефект и был найден. Разделяет **верх тела** знака над базовой
 * линией: у правильной строчной тело стоит на росте строчной буквы,
 * у сломанной — на росте прописной. Верхний значок в счёт не идёт, он отделён
 * разрывом; у знаков с хвостиком снизу хвостик верха тела не меняет.
 *
 * Базовая линия берётся из самой картинки: низ чернил базовой строчной буквы
 * (`a c e l n o s z` — ни у одной нет свисающей части).
 *
 * **Браузер этот инструмент не водит**, тем же доводом, что `frames.mjs`:
 * страница расставляет знаки и отдаёт их прямоугольники, сессия снимает кадр,
 * инструмент разбирает пиксели и выносит вердикт.
 *
 * Код возврата: `0` — чисто, `1` — есть сломанные или неразделимые,
 * `2` — инструмент не смог прочитать вход.
 */

import { existsSync, readFileSync } from 'node:fs';
import { sep } from 'node:path';
import { decodePng } from './pixels.mjs';

/** Девять польских букв с диакритикой и их основы, оба регистра. */
export const БУКВЫ = [
  { диак: 'ą', ДИАК: 'Ą', основа: 'a', ОСНОВА: 'A' },
  { диак: 'ć', ДИАК: 'Ć', основа: 'c', ОСНОВА: 'C' },
  { диак: 'ę', ДИАК: 'Ę', основа: 'e', ОСНОВА: 'E' },
  { диак: 'ł', ДИАК: 'Ł', основа: 'l', ОСНОВА: 'L', слитный: true },
  { диак: 'ń', ДИАК: 'Ń', основа: 'n', ОСНОВА: 'N' },
  { диак: 'ó', ДИАК: 'Ó', основа: 'o', ОСНОВА: 'O' },
  { диак: 'ś', ДИАК: 'Ś', основа: 's', ОСНОВА: 'S' },
  { диак: 'ź', ДИАК: 'Ź', основа: 'z', ОСНОВА: 'Z' },
  { диак: 'ż', ДИАК: 'Ż', основа: 'z', ОСНОВА: 'Z' },
];

/** Десять типографических ролей витрины — охват на будущее, не под случай. */
export const РОЛИ = [
  't-display', 't-headline', 't-title', 't-lead', 't-body',
  't-caption', 't-label', 't-micro', 't-year', 't-button',
];

/**
 * Скрипт страницы: расставляет знаки по клеткам и возвращает их прямоугольники.
 * `text-transform` у клетки снят намеренно — меряется сам глиф; настоящий
 * регистр роли возвращается отдельным полем, и роль под `uppercase` вердиктом
 * не судится, потому что дефект строчных на ней не виден.
 */
export const РАЗМЕТКА = (роли = РОЛИ, кегль = 60) => `(async () => {
  await document.fonts.ready;
  const роли = ${JSON.stringify(роли)};
  const буквы = ${JSON.stringify(БУКВЫ)};
  const К = ${кегль};
  const Ш = Math.round(К * 1.35), В = Math.round(К * 1.85);

  const стол = document.createElement('div');
  стол.style.cssText = 'position:absolute;left:0;top:0;z-index:2147483647;background:#000;padding:0;margin:0;font-size:0';
  document.body.style.margin = '0';

  const ячейки = [];
  for (const роль of роли) {
    const строка = document.createElement('div');
    строка.style.cssText = 'white-space:nowrap;font-size:0';
    for (const б of буквы) {
      for (const [вид, ch] of [['основа', б.основа], ['диак', б.диак], ['ОСНОВА', б.ОСНОВА], ['ДИАК', б.ДИАК]]) {
        const к = document.createElement('span');
        к.className = роль;
        к.style.cssText = 'display:inline-block;width:' + Ш + 'px;height:' + В + 'px;' +
          'font-size:' + К + 'px;line-height:' + В + 'px;text-align:center;color:#fff;' +
          'text-transform:none;letter-spacing:normal;vertical-align:top;overflow:hidden';
        к.textContent = ch;
        строка.appendChild(к);
        ячейки.push({ роль, буква: б.диак, вид, знак: ch, узел: к });
      }
    }
    стол.appendChild(строка);
  }
  document.body.insertBefore(стол, document.body.firstChild);
  window.scrollTo({ top: 0, behavior: 'instant' });
  await new Promise(r => setTimeout(r, 400));

  const регистры = {};
  for (const роль of роли) {
    const п = document.createElement('span');
    п.className = роль;
    document.body.appendChild(п);
    const cs = getComputedStyle(п);
    регистры[роль] = { регистр: cs.textTransform, семья: cs.fontFamily.split(',')[0].replace(/["']/g, '').trim() };
    document.body.removeChild(п);
  }

  const итог = ячейки.map((я) => {
    const r = я.узел.getBoundingClientRect();
    return { роль: я.роль, буква: я.буква, вид: я.вид, знак: я.знак,
      ...регистры[я.роль],
      x: Math.round(r.left), y: Math.round(r.top + window.scrollY),
      w: Math.round(r.width), h: Math.round(r.height) };
  });
  return { ячейки: итог, ширина: Math.ceil(стол.getBoundingClientRect().width),
           высота: Math.ceil(стол.getBoundingClientRect().height) };
})()`;

/** Профиль чернил клетки: какие строки её высоты несут хоть один светлый пиксель. */
function профиль(img, я) {
  const ch = img.channels;
  const out = [];
  for (let y = я.y; y < Math.min(я.y + я.h, img.height); y += 1) {
    let есть = false;
    for (let x = я.x; x < Math.min(я.x + я.w, img.width); x += 1) {
      const i = (y * img.width + x) * ch;
      if (img.data[i] > 90 || img.data[i + 1] > 90 || img.data[i + 2] > 90) { есть = true; break; }
    }
    out.push(есть);
  }
  return out;
}

const первая = (p) => p.indexOf(true);
const последняя = (p) => p.lastIndexOf(true);

/** Верх нижней сплошной полосы: от низа чернил вверх до первого разрыва. */
function верхТела(p) {
  let i = последняя(p);
  if (i < 0) return -1;
  while (i - 1 >= 0 && p[i - 1]) i -= 1;
  return i;
}

/**
 * Вердикт по одной букве одной роли.
 *
 * `неразделимо` — отдельный исход, а не тихий пропуск: если верхний значок
 * слился с телом, полоса одна, и мера ничего не говорит. Такое смотрится
 * глазами, а не засчитывается в чистые.
 */
export function разбор(четвёрка) {
  const { основа, диак, ОСНОВА, слитный } = четвёрка;
  if (!основа || !диак || !ОСНОВА) return { исход: 'нет данных' };
  const база = последняя(основа.профиль); // базовые буквы стоят на линии
  const рост = база - первая(основа.профиль);
  const РОСТ = база - первая(ОСНОВА.профиль);
  const тело = база - верхТела(диак.профиль);
  const полн = база - первая(диак.профиль);

  // `ł` — единственная, у кого значок ПЕРЕСЕКАЕТ ствол: полосы не две, а одна,
  // и «верх тела» о ней ничего не говорит. Её судит полная высота: у правильной
  // она равна росту строчной `l`. Порог 0,12 — измерен: Manrope даёт 0,00,
  // Cinzel 0,20.
  if (слитный) {
    const отклон = +(Math.abs(полн - рост) / рост).toFixed(3);
    return { исход: отклон > 0.12 ? 'сломана' : 'чисто', рост, РОСТ, тело: полн, полн, доля: отклон };
  }

  if (РОСТ <= рост) return { исход: 'неразделимо', рост, РОСТ, тело, полн };

  // Доля подъёма тела от роста строчной к росту прописной. Измерено 2026-09-09
  // на двух гарнитурах сайта: Manrope 0,00–0,25, Cinzel 0,54–0,58 у сломанных
  // и 0,00 у верной `ó`. Пороги стоят в этом зазоре с запасом с обеих сторон.
  const доля = +((тело - рост) / (РОСТ - рост)).toFixed(3);
  if (доля > 0.4) return { исход: 'сломана', рост, РОСТ, тело, полн, доля };
  if (доля < 0.32) return { исход: 'чисто', рост, РОСТ, тело, полн, доля };
  return { исход: 'на грани', рост, РОСТ, тело, полн, доля };
}

/** Вердикт по всему кадру. */
export function вердикт(ячейки, img) {
  const по = new Map();
  for (const я of ячейки) {
    const ключ = `${я.роль}|${я.буква}`;
    if (!по.has(ключ)) {
      const б = БУКВЫ.find((x) => x.диак === я.буква);
      по.set(ключ, { роль: я.роль, буква: я.буква, регистр: я.регистр, семья: я.семья, слитный: Boolean(б && б.слитный) });
    }
    по.get(ключ)[я.вид] = { ...я, профиль: профиль(img, я) };
  }
  const строки = [...по.values()].map((ч) => ({ ...ч, ...разбор(ч) }));
  const судимые = строки.filter((с) => с.регистр !== 'uppercase');
  return {
    строки,
    судимые,
    сломанные: судимые.filter((с) => с.исход === 'сломана'),
    неразделимые: судимые.filter((с) => с.исход === 'неразделимо'),
    награни: судимые.filter((с) => с.исход === 'на грани'),
    подзащитой: строки.filter((с) => с.регистр === 'uppercase' && с.исход === 'сломана'),
  };
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split(sep).join('/'))) {
  const [, , cmd, файлЯчеек, файлКадра] = process.argv;
  if (cmd === 'protocol') {
    console.log('ПОРЯДОК:');
    console.log('1. Собрать сайт и поднять прод-превью (не dev-сервер).');
    console.log('2. Выполнить скрипт ниже на КАЖДОЙ собранной странице: он вернёт ячейки и размер полосы.');
    console.log('3. Снять полностраничный кадр этой ширины и высоты.');
    console.log('4. node core/accept/glyphs.mjs check <ячейки.json> <кадр.png>');
    console.log('');
    console.log('СКРИПТ:');
    console.log(РАЗМЕТКА());
  } else if (cmd === 'check' && файлЯчеек && файлКадра) {
    if (!existsSync(файлЯчеек) || !existsSync(файлКадра)) {
      console.error('нет файла ячеек или кадра');
      process.exit(2);
    }
    const ячейки = JSON.parse(readFileSync(файлЯчеек, 'utf8'));
    const img = decodePng(readFileSync(файлКадра));
    const r = вердикт(Array.isArray(ячейки) ? ячейки : ячейки.ячейки, img);

    for (const роль of РОЛИ) {
      const свои = r.строки.filter((с) => с.роль === роль);
      if (!свои.length) continue;
      const п = свои[0];
      const плохие = свои.filter((с) => с.исход === 'сломана').map((с) => с.буква);
      const серые = свои.filter((с) => с.исход === 'неразделимо' || с.исход === 'на грани').map((с) => с.буква);
      const хвост = плохие.length ? 'СЛОМАНЫ: ' + плохие.join(' ') : 'чисто';
      const щит = п.регистр === 'uppercase' ? ' (под защитой uppercase — вердиктом не судится)' : '';
      console.log(`${роль.padEnd(12)} ${п.семья.padEnd(9)} ${хвост}${серые.length ? ' | смотреть глазами: ' + серые.join(' ') : ''}${щит}`);
    }
    console.log('');
    if (r.подзащитой.length) {
      console.log(`Под защитой uppercase скрыто сломанных знаков: ${r.подзащитой.length}. Снятие регистра вернёт дефект.`);
    }
    const беда = r.сломанные.length + r.неразделимые.length;
    if (беда) {
      console.log(`Судимых знаков ${r.судимые.length}; сломано ${r.сломанные.length}, неразделимо ${r.неразделимые.length}.`);
      process.exit(1);
    }
    console.log(`Все ${r.судимые.length} судимых знаков нарисованы строчными глифами.`);
  } else {
    console.error('node core/accept/glyphs.mjs protocol');
    console.error('node core/accept/glyphs.mjs check <ячейки.json> <кадр.png>');
    process.exit(2);
  }
}

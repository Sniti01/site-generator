#!/usr/bin/env node
/**
 * Приёмка: ВЕСЬ CSS сборки — подключённые листы плюс встроенные в страницы
 * блоки `<style>`.
 *
 *   node core/accept/build-css.mjs <папка dist> [файл.css]
 *
 * **Мера была слепа, и это измерено 2026-09-10.** Сверка троек читала только
 * `dist/_astro/*.css`. Astro встраивает стили страницы прямо в её HTML, когда
 * лист мал, — и на первой странице волны 1 счёт показал рост **на два
 * правила** там, где их прибавилось **почти тридцать**: двадцать восемь лежали
 * в `<style>` внутри страницы и в меру не попадали. С того момента, как
 * у страницы появляются встроенные стили, счёт по одним листам перестаёт
 * описывать страницу — и молчит об этом.
 *
 * **Порядок сбора постоянный:** листы по имени, затем страницы по пути.
 * Совпадать с порядком каскада он не обязан и не пытается: мера считает
 * мультимножество правил, а не их приоритет. Постоянство нужно другому —
 * чтобы две сборки собирались одинаково и разница означала разницу сборок,
 * а не порядка чтения.
 *
 * Живёт отдельным файлом, а не внутри `css-triples.mjs`, по той же причине,
 * по которой гашение скрутов живёт в `html-diff.mjs`: собирать вход и считать
 * правила — разные работы, и вход нужен ещё и `zero-view.mjs`.
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, sep } from 'node:path';

/** Все `*.html` сборки, в постоянном порядке по пути. */
export function страницыСборки(dist) {
  const out = [];
  const обойти = (d) => {
    for (const имя of readdirSync(d).sort()) {
      const путь = join(d, имя);
      if (statSync(путь).isDirectory()) обойти(путь);
      else if (имя.endsWith('.html')) out.push(путь);
    }
  };
  обойти(dist);
  return out;
}

/** Встроенные блоки `<style>` одной страницы, в порядке появления. */
export function встроенные(html) {
  return [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]);
}

/**
 * Весь CSS сборки одной строкой плюс счёт того, откуда он собран.
 * Счёт печатается наружу намеренно: «сколько кусков и сколько страниц» —
 * та самая величина, молчание о которой и сделало меру слепой.
 */
export function весьCss(dist) {
  const части = [];
  let листов = 0;
  const astro = join(dist, '_astro');
  try {
    for (const f of readdirSync(astro).filter((x) => x.endsWith('.css')).sort()) {
      части.push(readFileSync(join(astro, f), 'utf8'));
      листов += 1;
    }
  } catch {
    // Папки `_astro` может не быть: сборка без единого листа — тоже сборка.
  }

  const страницы = страницыСборки(dist);
  let блоков = 0;
  for (const путь of страницы) {
    for (const кусок of встроенные(readFileSync(путь, 'utf8'))) {
      части.push(кусок);
      блоков += 1;
    }
  }

  return { css: части.join('\n'), листов, блоков, страниц: страницы.length };
}

/**
 * Вход меры: файл читается как есть, папка собирается целиком.
 * Позволяет старым вызовам с файлом работать без правок, а новым — передавать
 * `dist` и не думать о встроенных стилях.
 */
export function прочитатьCss(путь) {
  if (statSync(путь).isDirectory()) {
    const r = весьCss(путь);
    return {
      текст: r.css,
      откуда: `сборка: листов ${r.листов}, встроенных блоков ${r.блоков}, страниц ${r.страниц}`,
    };
  }
  return { текст: readFileSync(путь, 'utf8'), откуда: null };
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split(sep).join('/'))) {
  const [, , dist, out] = process.argv;
  if (!dist) {
    console.error('node core/accept/build-css.mjs <папка dist> [файл.css]');
    process.exit(2);
  }
  const r = весьCss(dist);
  console.log(`листов ${r.листов}, встроенных блоков ${r.блоков}, страниц ${r.страниц}, знаков ${r.css.length}`);
  if (out) {
    writeFileSync(out, r.css);
    console.log(`записано: ${out}`);
  }
}

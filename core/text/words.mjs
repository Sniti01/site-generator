/**
 * СЛОВА И 8-ГРАММЫ — одна модель слов для страниц, брифов и документов корпуса (П102 блок А).
 *
 * Слово — буквы и цифры Юникода с апострофами внутри, строчными; апострофы ’ ‘ ` сведены к '
 * (правило сторожа брифов и среза окончаний). Имена сайта (официальные названия игр, данные
 * сайта) сворачиваются в одно слово `§imya§` — имя собственное, а не формулировка: фраза
 * конкурента из названия игры и двух слов вокруг — не чужой текст (сторож брифов, П85; цена —
 * длинное название съедает слова фразы, R1-BRIFY-11).
 *
 * Два режима 8-граммы: ТОЧНЫЙ (слова как есть) и СРЕЗ ОКОНЧАНИЙ (правило среза сессии 15:
 * `'s`, `-ies` → `-y`, `-es`/`-s` у слов от трёх букв): фраза конкурента с другим числом или
 * притяжательным не проходит под видом своей. Срез делается после свёртки имён.
 *
 * Хеш 8-граммы — 53 бита (cyrb53, целое в пределах `Number`): у прежнего указателя было 32 бита
 * SHA-1, и на странице из тысяч 8-грамм против миллиона в корпусе ложное совпадение хеша
 * ожидалось почти на каждой странице — его гасило только подтверждение текстом. Здесь совпадение
 * хеша тоже подтверждается словами документа (`corpus.mjs`), так что столкновение хешей находкой
 * не становится.
 */

/** Длина последовательности слов, совпадение которой — чужая формулировка. */
export const N_GRAM = 8;
/** Режимы сравнения: точный и со срезом окончаний. */
export const REZHIMY = ['tochno', 'srez'];

/** Слова строки. */
export const slova = (s) =>
  (s.toLowerCase().replace(/[’‘`]/g, "'").match(/[\p{L}\p{N}']+/gu) ?? []).map((w) => w.replace(/^'+|'+$/g, '')).filter(Boolean);

/** Имена сайта словами, длинные первыми (чтобы «Max Payne 3» не съел начало длинного названия). */
export const imenaSlovami = (imena) => imena.map((n) => slova(n)).filter((w) => w.length).sort((a, b) => b.length - a.length);

/**
 * Свёртка имён: каждое вхождение имени — одно слово `§imya§`. `ws` — слова (или объекты со
 * словом в поле `w`, тогда свёрнутому достаются поля первого слова и `do` — индекс последнего).
 */
export function bezImen(ws, imenaSl) {
  const w = (x) => (typeof x === 'string' ? x : x.w);
  const out = [];
  for (let i = 0; i < ws.length; ) {
    const im = imenaSl.find((n) => n.every((s, j) => i + j < ws.length && w(ws[i + j]) === s));
    if (im) {
      out.push(typeof ws[i] === 'string' ? '§imya§' : { ...ws[i], w: '§imya§', do: i + im.length - 1 });
      i += im.length;
    } else out.push(ws[i++]);
  }
  return out;
}

/** Срез окончаний одного слова (правило среза сессии 15). */
export const srez = (w) => w.replace(/'s$/, '').replace(/(ies)$/, 'y').replace(/([a-z]{3,})(es|s)$/, '$1');

/** Слова в режиме: точный — как есть, срез — каждое срезом. */
export const vRezhime = (ws, rezhim) => (rezhim === 'srez' ? ws.map(srez) : ws);

/** Хеш 8-граммы (строка слов через пробел) — cyrb53: целое 0…2^53−1. */
export function hesh(g) {
  let h1 = 0xdeadbeef;
  let h2 = 0x41c6ce57;
  for (let i = 0; i < g.length; i++) {
    const c = g.charCodeAt(i);
    h1 = Math.imul(h1 ^ c, 2654435761);
    h2 = Math.imul(h2 ^ c, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507);
  h1 ^= Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507);
  h2 ^= Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return 4294967296 * (2097151 & h2) + (h1 >>> 0);
}

/**
 * Адреса в тексте — пробелом, знаками адреса по RFC 3986 (судья глав сессии 19, раунд 4: слова,
 * приклеенные к адресу знаком, который пробелом не считается, остаются словами). Адрес — не
 * формулировка: слаг несёт заголовок чужой статьи (R1-BRIFY-2).
 */
export const bezAdresov = (t) => t.replace(/https?:\/\/[A-Za-z0-9\-._~:/?#[\]@!$&'()*+,;=%]+/g, ' ');

  check('шум: совпали — 0', '0', кратко(оц(э, клон(э), [З()])), 'тот же буфер — ни одного различия, вне допуска null');
  check('шум: дифф в зоне ≤ макс — в допуске', 'в:z=1/1', кратко(оц(э, с1(5, 5, 0, 1), [З()])), 'Δ1 при макс 2 — субпиксель отдан зоне');

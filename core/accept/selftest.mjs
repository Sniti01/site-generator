  const бросает = (зоны, слово) => { try { проверитьЗоны(зоны); return 'прошло'; } catch (e) { return e.message.includes(слово) ? `отказ: ${слово}` : `иной сбой: ${e.message}`; } };
  check('шум: негодное регулярное выражение — отказ с именем зоны', 'отказ: «x»', бросает([З({ зона: 'x', кадры: '[' })], '«x»'), 'опечатка в «кадры» не молчит');
